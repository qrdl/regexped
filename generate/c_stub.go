// cStub generates C stub files (.h and .c) for all regexp entries in cfg.
// out is the stub file path from config (e.g. "stub.h"); both .h and .c are derived from it.
// If out == "-", both files' content is written concatenated to stdout.
func cStub(cfg config.BuildConfig, out string) error {
	hBase := "stub.h"
	if out != "-" {
		base := strings.TrimSuffix(out, filepath.Ext(out))
		hBase = filepath.Base(base + ".h")
	}

	hContent, cContent, err := genCStubFilesWithSets(cfg, hBase)
	if err != nil {
		return fmt.Errorf("generate C stub: %w", err)
	}
	if hContent == "" {
		return nil
	}
	// See jsStub: the namespace applies on the stdout path too, and to BOTH
	// halves.
	hContent = applyNamespace(cfg, "c", hContent)
	cContent = applyNamespace(cfg, "c", cContent)
	if out == "-" {
		_, err := os.Stdout.WriteString(hContent + cContent)
		return err
	}
	base := strings.TrimSuffix(out, filepath.Ext(out))
	if err := writeStub(base+".h", []byte(hContent)); err != nil {
		return err
	}
	return writeStub(base+".c", []byte(cContent))
}

// cTypesPreambleNotes is the shared head of every generated C header: the
// include guard, the position/extent types and the error sentinels, plus, when
// wantNotes, the switch that lets a find or groups iterator allocate its
// search's notes (search_stub.go). Shared so the component generator emits a
// byte-identical preamble rather than a lookalike — the header IS the API, and
// two copies would drift.
func cTypesPreambleNotes(wantCache, wantNotes bool) string {
	s := cTypesPreambleCache(wantCache)
	if wantNotes {
		s += cSearchPreamble
	}
	return s
}

func cTypesPreambleCache(wantCache bool) string {
	var hb strings.Builder
	hb.WriteString("/* Auto-generated by regexped. Do not edit. */\n")
	hb.WriteString("#pragma once\n\n")
	hb.WriteString("#ifndef REGEXPED_TYPES_DEFINED\n")
	hb.WriteString("#define REGEXPED_TYPES_DEFINED\n")
	// Types: size_t for lengths, offsets and
	// capacities and ONLY those — it means "can hold the size of any object",
	// which a pattern id is not. ptrdiff_t for positions coming back, because
	// -1 is the sentinel for "no match" / "group absent" and an unsigned type
	// has no room for it; this is the read() pairing. int for pattern ids and
	// counts, which keeps a negative slot free for a future failure and avoids
	// the signed/unsigned warning in for (int i = 0; i < n; i++).
	hb.WriteString("#include <stddef.h>   /* size_t, ptrdiff_t -- freestanding-required, no libc */\n\n")
	hb.WriteString("typedef struct { ptrdiff_t start, end; } rx_match_t;\n")
	// The `name` field is gone: identity is the INDEX now, so
	// the name pointer duplicated the index-aligned table and cost a pointer per group.
	hb.WriteString("typedef struct { ptrdiff_t start, end; } rx_group_t;\n")
	hb.WriteString("typedef struct { int pattern_id; ptrdiff_t start, end; } rx_set_match_t;\n")
	hb.WriteString("\n")
	hb.WriteString("/* Returned when the Backtracking engine exhausted its backtrack-frame\n")
	hb.WriteString("   budget on this input. The engine abandoned part of the search space, so\n")
	hb.WriteString("   whether the input matches is UNKNOWN -- this is NOT \"no match\". Treat it\n")
	hb.WriteString("   as an error: shorten the input, or raise the pattern's frame budget.\n")
	hb.WriteString("   C has no unwinding, so the sentinel is RETURNED: a match function\n")
	hb.WriteString("   returns it directly, and an iterator's _next returns it as its status\n")
	hb.WriteString("   instead of 1 (wrote a match) or 0 (finished). Test it EXACTLY -- a\n")
	hb.WriteString("   plain < 0 check reports \"unknown\" as a confident \"no\".\n")
	hb.WriteString("   See docs/engines.md. */\n")
	fmt.Fprintf(&hb, "#define RX_ERR_BT_OVERFLOW (%d)\n", btOverflow)
	hb.WriteString("/* The overlapping answer cache's header is malformed -- a stride below 1,\n")
	hb.WriteString("   or a layout that does not describe what the sweep would have written.\n")
	hb.WriteString("   The scan is UNKNOWN, not finished. A scanner initialised by this\n")
	hb.WriteString("   header's _init cannot produce it: the region and the stride come from\n")
	hb.WriteString("   one formula. A caller building its own descriptor, or sharing one\n")
	hb.WriteString("   region between two scanners, can. See docs/sets.md. */\n")
	fmt.Fprintf(&hb, "#define RX_ERR_MALFORMED_CACHE (%d)\n", malformedCache)
	hb.WriteString("/* An overlapping set's find was asked for an offset BELOW where its\n")
	hb.WriteString("   answer cache was built: the scan went backwards, and its result is\n")
	hb.WriteString("   UNKNOWN. Offsets must never go backwards within one scan. Detection is\n")
	hb.WriteString("   best effort, so its absence is not a guarantee. The engine's own value,\n")
	hb.WriteString("   passed through unchanged -- every error code means the same thing in\n")
	hb.WriteString("   every language, which is why it is not -5. See docs/sets.md. */\n")
	fmt.Fprintf(&hb, "#define RX_ERR_OUT_OF_ORDER (%d)\n", outOfOrder)
	hb.WriteString("/* Argument errors from the scanner initialisers. */\n")
	hb.WriteString("#define RX_ERR_NULL_ARG    (-3)\n")
	hb.WriteString("#define RX_ERR_RANGE       (-5)\n")
	hb.WriteString("#endif\n\n")

	// The OVERLAPPING answer cache is the one thing in this header that needs
	// an allocator, and C is the only target that might not have one: Rust, Go
	// and AssemblyScript ship runtimes that allocate, JavaScript has an engine,
	// and this header is documented as needing no libc or sysroot at all.
	//
	// So it is detected rather than demanded. With a sysroot an overlapping
	// drive is LINEAR; without one the cache is declined and the drive walks,
	// which is exactly what it did before the cache existed — the answers are
	// identical either way.
	// Emitted ONLY where some set actually has a cache. A config with no sets,
	// or with none overlapping, has nothing to allocate for, and a header that
	// carried the machinery anyway would pull <stdlib.h> into builds that
	// document themselves as needing no libc — and ship a square root nothing
	// calls.
	if !wantCache {
		return hb.String()
	}
	hb.WriteString(`/* The overlapping answer cache needs an allocator, and a freestanding
   wasm32 build of this header has none. Detected, not demanded: define
   RX_SET_CACHE yourself to force it on or off.

   ON  -> an overlapping set's find is linear.
   OFF -> it walks, quadratic, with identical answers -- unless you hand the
          scanner a buffer with <find>_set_cache, which needs no allocator.

   Your build decides this, not your source.

   A -nostdlib BUILD MUST PASS -DRX_SET_CACHE=0. The preprocessor cannot see
   link flags: -nostdlib removes libc from the LINK, not <stdlib.h> from the
   include path, and a wasi-sdk clang always finds that header. Without the
   define this file then references malloc and free and the link fails on
   undefined symbols. */
#ifndef RX_SET_CACHE
#  if defined(__has_include)
#    if __has_include(<stdlib.h>)
#      define RX_SET_CACHE 1
#    else
#      define RX_SET_CACHE 0
#    endif
#  else
#    define RX_SET_CACHE 0
#  endif
#endif

#if RX_SET_CACHE
#include <stdlib.h>
#endif
/* The stride is a square root, and it has to be THE square root: every other
   stub computes it in IEEE double and truncates, and a stride one apart from
   the region it sized is a header the sweep reports as malformed. A Newton
   iteration stood here and is not IEEE sqrt -- it can land an ulp away, which
   trunc() then turns into a different integer.

   __builtin_sqrt lowers to the wasm f64.sqrt instruction with no libm and no
   call, so this costs nothing and is exact. */
#define rx_sqrt_(x) __builtin_sqrt(x)

`)
	return hb.String()
}

// genCStubFiles generates the content for both the .h and .c stub files.
// hBasename is the bare filename of the header (e.g. "stub.h") used in the #include directive.
func genCStubFiles(entries []config.RegexEntry, importModule, hBasename string, wantCache bool) (hContent, cContent string, err error) {
	return genCStubFilesSized(entries, importModule, hBasename, wantCache, nil)
}

// genCStubFilesSized is genCStubFiles with each export's search block
// (search_stub.go); nil sizes means none.
func genCStubFilesSized(entries []config.RegexEntry, importModule, hBasename string, wantCache bool, sizes map[string]compile.SearchSize) (hContent, cContent string, err error) {
	type entryParts struct{ h, c string }
	var parts []entryParts
	for _, re := range entries {
		h, c, _, e := genCPartsForEntrySized(re, importModule, sizes)
		if e != nil {
			return "", "", e
		}
		if h != "" {
			parts = append(parts, entryParts{h, c})
		}
	}

	var hb, cb strings.Builder

	hb.WriteString(cTypesPreambleNotes(wantCache, anySearchBlock(sizes)))

	// .c file
	cb.WriteString("/* Auto-generated by regexped. Do not edit. */\n")
	fmt.Fprintf(&cb, "#include \"%s\"\n\n", hBasename)
	if anySearchBlock(sizes) {
		cb.WriteString(cSearchCPreamble(importModule))
	}

	for _, p := range parts {
		hb.WriteString(p.h)
		cb.WriteString(p.c)
	}

	return hb.String(), cb.String(), nil
}

// cStubWithSets updates genCStubFiles to also handle sets.
func genCStubFilesWithSets(cfg config.BuildConfig, hBasename string) (hContent, cContent string, err error) {
	hasIndividual := false
	for _, re := range cfg.Regexps {
		if re.MatchFunc != "" || re.FindFunc != "" || re.GroupsFunc != "" {
			hasIndividual = true
			break
		}
	}
	if !hasIndividual && !hasSetExports(cfg) {
		return "", "", nil
	}
	shapes := newSetShapes(cfg)
	sizes := searchSizesFor(cfg)
	hContent, cContent, err = genCStubFilesSized(cfg.Regexps, cfg.ImportModule, hBasename, shapes.anyWantsCache(), sizes)
	if err != nil {
		return
	}
	if !hasSetExports(cfg) {
		return
	}
	var hb, cb strings.Builder
	hb.WriteString(hContent)
	cb.WriteString(cContent)
	for setIdx, s := range cfg.Sets {
		n := patternsInSet(s, cfg)
		konst := screamingCase(s.Name) + "_PATTERN_COUNT"
		idN := idSpaceSize(s, cfg)
		idKonst := screamingCase(s.Name) + "_ID_SPACE"
		wide := shapes.wideAll(setIdx)

		hb.WriteString(cSetConstDecls(s.Name, konst, idKonst, n, idN))

		imp := func(name, sig string) {
			fmt.Fprintf(&hb, "__attribute__((import_module(%q), import_name(%q)))\n%s\n", cfg.ImportModule, name, sig)
		}
		// Parameter lists come from the ONE descriptor in set_stub.go; only
		// the C spelling of each is decided here. C puts the return type
		// FIRST, which is why this builds the whole declaration rather than
		// just a parameter list.
		setCaps := setCapabilities(s, cfg, wide)
		decl := func(kind string) string {
			capability := mustCapByKind(setCaps, kind, "C")
			return fmt.Sprintf("%s ffi_%s(%s);", cABIRet(capability.Ret), capability.Export,
				capability.render(cABIParam, ", "))
		}
		if s.MatchAny != "" {
			imp(s.MatchAny, decl("match_any"))
			hb.WriteString(cSetMatchAnyDecl(s.MatchAny))
			fmt.Fprintf(&cb, `int %s(const char *input, size_t len) { return ffi_%s(input, (int)len); }
`, s.MatchAny, s.MatchAny)
		}
		if s.MatchAll != "" {
			if wide {
				imp(s.MatchAll, decl("match_all"))
			} else {
				imp(s.MatchAll, decl("match_all"))
			}
			// C99's `static N` in an array parameter declarator
			// means "the caller must pass at least N elements" — GCC and Clang
			// diagnose a smaller array at the CALL SITE, it rules out NULL,
			// and it self-documents. A plain int patterns[N] would decay to
			// int * and be documentation only.
			//
			// The size is PATTERN_COUNT, not ID_SPACE: the body loops k over
			// the id space and appends one entry per set bit, and only
			// patterns IN the set have bits, so at most PATTERN_COUNT entries
			// are ever written. ID_SPACE stays correct for things indexed BY
			// an id — the gate array, the _all bitmap — and this is a LIST of
			// ids, not an id-indexed array.
			hb.WriteString(cSetMatchAllDecl(s.MatchAll, konst))
			if wide {
				fmt.Fprintf(&cb, `int %[1]s(const char *input, size_t len, int patterns[static %[3]s]) {
    unsigned char bits[(%[2]s + 7) / 8] = {0};
    int n = ffi_%[1]s(input, (int)len, bits);
    if (n < 0) return n; /* RX_ERR_BT_OVERFLOW: result unknown, not empty */
    int c = 0;
    for (int k = 0; k < %[2]s; k++) if (bits[k / 8] & (1u << (k %% 8))) patterns[c++] = k;
    return c;
}
`, s.MatchAll, idKonst, konst)
			} else {
				fmt.Fprintf(&cb, `int %[1]s(const char *input, size_t len, int patterns[static %[3]s]) {
    long long raw = ffi_%[1]s(input, (int)len);
    /* NO overflow sentinel here: the narrow form's return IS the bitmask, so
       every 64-bit value is a legal answer. -2 means ids 1..63 matched and id 0
       did not, which a sentinel test would report as an engine failure. The
       real sentinel cannot reach this form — a Backtracking member forces the
       wide one. */
    unsigned long long mask = (unsigned long long)raw;
    int c = 0;
    for (int k = 0; k < %[2]s; k++) if (mask & (1ULL << k)) patterns[c++] = k;
    return c;
}
`, s.MatchAll, idKonst, konst)
			}
		}
		if s.ScanAny != "" {
			imp(s.ScanAny, decl("scan_any"))
			hb.WriteString(cSetScanAnyDecl(s.ScanAny))
			fmt.Fprintf(&cb, `int %[1]s(const char *input, size_t len, size_t offset) {
    return ffi_%[1]s(input, (int)len, (int)offset);
}
`, s.ScanAny)
		}
		if s.ScanAll != "" {
			if wide {
				imp(s.ScanAll, decl("scan_all"))
			} else {
				imp(s.ScanAll, decl("scan_all"))
			}
			hb.WriteString(cSetScanAllDecl(s.ScanAll, konst))
			if wide {
				fmt.Fprintf(&cb, `int %[1]s(const char *input, size_t len, size_t offset, int patterns[static %[3]s]) {
    unsigned char bits[(%[2]s + 7) / 8] = {0};
    int n = ffi_%[1]s(input, (int)len, (int)offset, bits);
    if (n < 0) return n; /* RX_ERR_BT_OVERFLOW: result unknown, not empty */
    int c = 0;
    for (int k = 0; k < %[2]s; k++) if (bits[k / 8] & (1u << (k %% 8))) patterns[c++] = k;
    return c;
}
`, s.ScanAll, idKonst, konst)
			} else {
				fmt.Fprintf(&cb, `int %[1]s(const char *input, size_t len, size_t offset, int patterns[static %[3]s]) {
    long long raw = ffi_%[1]s(input, (int)len, (int)offset);
    /* NO overflow sentinel here: the narrow form's return IS the bitmask, so
       every 64-bit value is a legal answer. -2 means ids 1..63 matched and id 0
       did not, which a sentinel test would report as an engine failure. The
       real sentinel cannot reach this form — a Backtracking member forces the
       wide one. */
    unsigned long long mask = (unsigned long long)raw;
    int c = 0;
    for (int k = 0; k < %[2]s; k++) if (mask & (1ULL << k)) patterns[c++] = k;
    return c;
}
`, s.ScanAll, idKonst, konst)
			}
		}
		if s.Find != "" {
			scannerType := "rx_" + setConstBase(s.Name) + "_scanner_t"
			// EVERY set with `find` takes the gate array, overlapping included
			// — the branch that omitted it was unreachable
			// and is gone.
			imp(s.Find, decl("find"))
			blocks := sizes[s.Find].Blocks
			gateField := cSetGateField(idKonst, len(blocks))
			gateInit := fmt.Sprintf("    for (size_t k = 0; k < %s; k++) s->gates[k] = 0;\n", idKonst)
			// The SCRATCH DESCRIPTOR the export takes in place of a bare gate
			// pointer: magic, gate pointer, and the answer cache — the region
			// allocated below for a cache-eligible overlapping set, zero
			// otherwise.
			//
			// Built before EACH call rather than in _init, because field 1 is a
			// pointer INTO the scanner: a struct that was moved or copied would
			// otherwise leave the copy pointing at the original's gates. Copying
			// an INITIALISED scanner is not sanctioned any more — with an owned
			// cache it double-frees — and the header says so.
			cacheSet := "s->scratch[2] = 0, s->scratch[3] = 0"
			cacheField, cacheAlloc, cacheFree := "", "", ""
			cacheAPI := cSetNoCacheAPI(s.Find, scannerType)
			if sh := shapes.cacheShape(setIdx); sh.Offered() {
				consts := overlapCacheConstsFor(sh)
				// The CHECKPOINTED answer cache, and the ONE place the C stub
				// allocates.
				//
				// IT IS CONDITIONAL, because C is the only target whose
				// allocator lives outside the toolchain's own output. Rust,
				// Go and AssemblyScript ship a runtime that allocates and
				// JavaScript has an engine; a freestanding wasm32 build of this
				// header has nothing, which is why the header is documented as
				// needing no libc or sysroot. `__has_include(<stdlib.h>)`
				// settles it at COMPILE time with nothing for the consumer to
				// declare: with a sysroot the drive is linear, without one the
				// cache is declined and the drive walks unless the caller hands
				// a buffer over through `<find>_set_cache`. RX_SET_CACHE forces
				// either way.
				//
				// The sizing lives in ONE static function that _init,
				// `<find>_cache_bytes` and `<find>_set_cache` all call, so a
				// caller's buffer and the stub's own allocation cannot be sized
				// by two formulas.
				cacheField = cSetCacheFields
				cacheAPI = fmt.Sprintf(`/* The answer cache's size for an input of len, and its stride; 0 when the
   input is too long for one. ONE formula for _init, _cache_bytes and
   _set_cache. */
static size_t rx_%[9]s_cache_plan_(size_t len, unsigned *stride) {
    if (len > 0x7FFFFFFF) return 0;
    unsigned long long m = (unsigned long long)len + 1;
%[10]s    if (bytes > %[4]dULL) return 0;
%[11]s    *stride = (unsigned)k;
    return (size_t)bytes;
}

/* The header only: the engine reads nothing past it before the pass writes
   it, so zeroing the whole region would be a pass over memory the cache is
   about to fill anyway. Byte stores, so a caller's buffer needs no alignment. */
static void rx_%[9]s_cache_head_(void *mem, unsigned stride) {
    unsigned char *c = (unsigned char *)mem;
    for (size_t i = 0; i < %[7]d; i++) c[i] = 0;
    for (int i = 0; i < 4; i++) c[%[8]d + i] = (unsigned char)(stride >> (8 * i));
}

size_t %[9]s_cache_bytes(size_t len) {
    unsigned k;
    return rx_%[9]s_cache_plan_(len, &k);
}

int %[9]s_set_cache(%[12]s *s, void *buf, size_t bytes) {
    if (!s) return RX_ERR_NULL_ARG;
    unsigned k;
    size_t need = rx_%[9]s_cache_plan_(s->len, &k);
    if (need == 0) return 0; /* this input gets no cache: nothing to hand over */
    if (!buf) return RX_ERR_NULL_ARG;
    if (bytes < need) return RX_ERR_RANGE;
#if RX_SET_CACHE
    if (s->cache_own) free(s->cache);
#endif
    rx_%[9]s_cache_head_(buf, k);
    s->cache = (unsigned *)buf; s->cache_words = need / 4; s->cache_own = 0;
    return 0;
}

`, consts.Cells, sh.Patterns, consts.Hdr, consts.Max,
					consts.Row, consts.Cell, config.SetOverlapCheckpointHeaderBytes,
					config.SetOverlapHdrStrideOff, s.Find, cCachePart(sh, consts), cSweepPart(sh, consts), scannerType)
				cacheAlloc = fmt.Sprintf(`    /* Writes only: a scanner that owns a cache must be _free'd before it is
       initialised again, so nothing here reads what the struct held. */
    s->cache = 0; s->cache_words = 0; s->cache_own = 0;
#if RX_SET_CACHE
    {
        unsigned k;
        size_t bytes = rx_%[1]s_cache_plan_(len, &k);
        if (bytes) {
            s->cache = (unsigned *)malloc(bytes);
            if (s->cache) {
                rx_%[1]s_cache_head_(s->cache, k);
                s->cache_words = bytes / 4;
                s->cache_own = 1;
            }
        }
    }
#endif
`, s.Find)
				cacheFree = `#if RX_SET_CACHE
    if (s->cache_own) free(s->cache);
#endif
    s->cache = 0; s->cache_words = 0; s->cache_own = 0;
`
				cacheSet = "s->scratch[2] = (unsigned)(size_t)s->cache, " +
					"s->scratch[3] = (unsigned)(s->cache_words * 4)"
			}
			cb.WriteString(cacheAPI)
			cb.WriteString(cSetNotesPairDefs(s.Find, scannerType, blocks))
			gateField += cacheField + cSetBlockFields(blocks)
			gateInit += cacheAlloc
			gateArg := "(s->scratch[0] = " + fmt.Sprint(abi.FindScratchMagic) +
				"u, s->scratch[1] = (unsigned)(size_t)s->gates, " + cacheSet + ", s->scratch), "
			blockNotes, pendingCheck := "", ""
			// What the scanner owns, zeroed FIRST, before any argument check
			// can return: a later _free of a scanner whose _init failed must
			// find nothing to free.
			ownZero := ""
			if cacheField != "" {
				ownZero += "    s->cache = 0; s->cache_words = 0; s->cache_own = 0;\n"
			}
			if len(blocks) > 0 {
				ownZero += fmt.Sprintf("    for (size_t k = 0; k < %d; k++) s->notes[k] = 0;\n", len(blocks))
				if blocksBTMemo(blocks) {
					ownZero += fmt.Sprintf("    for (size_t k = 0; k < %d; k++) s->btmemos[k] = 0;\n", len(blocks))
				}
				ownZero += "    s->given = 0;\n    s->pending = 0;\n"
				pendingCheck = "    if (s->pending) { int e = s->pending; s->pending = 0; s->done = 1; return e; }\n"
			}
			if len(blocks) > 0 {
				btmemoInit, btmemoFree := "", ""
				if blocksBTMemo(blocks) {
					btmemoInit = "        s->btmemos[k] = 0;\n"
					btmemoFree = " if (s->btmemos[k]) { free(s->btmemos[k]); s->btmemos[k] = 0; }"
				}
				gateInit += fmt.Sprintf("    for (size_t k = 0; k < %d; k++) {\n"+
					"        for (int w = 0; w < %d; w++) s->blocks[k][w] = 0;\n        s->notes[k] = 0;\n%s    }\n",
					len(blocks), abi.SearchBlockBytes/8, btmemoInit)
				gateArg = "(s->scratch[0] = " + fmt.Sprint(abi.FindScratchMagicBlocks) +
					"u, s->scratch[1] = (unsigned)(size_t)s->gates, " + cacheSet +
					fmt.Sprintf(", s->scratch[4] = (unsigned)(size_t)s->blocks, s->scratch[5] = %du, s->scratch), ", len(blocks))
				for k, sz := range blocks {
					if sz.NotesBytes > 0 {
						blockNotes += fmt.Sprintf("    { int nerr = rx_search_notes_(s->blocks[%d], &s->notes[%d], s->len, %d, %s);\n"+
							"      if (nerr && !s->pending) s->pending = nerr; }\n", k, k, sz.NotesBytes, cSetNotesAt(s.Find, blocks, k, false))
					}
					if sz.BTMemoBytes > 0 {
						blockNotes += fmt.Sprintf("    { int nerr = rx_search_btmemo_(s->blocks[%d], &s->btmemos[%d], s->len, %d, %s);\n"+
							"      if (nerr && !s->pending) s->pending = nerr; }\n", k, k, sz.BTMemoBytes, cSetNotesAt(s.Find, blocks, k, true))
					}
				}
				cacheFree += fmt.Sprintf("#if RX_SEARCH_NOTES\n    for (size_t k = 0; k < %d; k++) {\n        if (s->notes[k]) { free(s->notes[k]); s->notes[k] = 0; }%s\n    }\n#endif\n", len(blocks), btmemoFree)
			}
			// The scanner is CALLER-owned, so two scans can be in flight
			// and _free followed by _init restarts one. The static
			// _next/_reset pair this replaces could do neither.
			//
			// The TUPLE BUFFER is the caller's too, for the reason given
			// for find_batch: a header with no allocator can only own storage
			// whose size is known at compile time, and PATTERN_COUNT tuples of
			// a several-thousand-pattern set is tens of kilobytes to bury in a
			// struct the caller is invited to put on the stack. The GATE array
			// stays inside — its length is a size the compiler knows, not one
			// the caller picks.
			//
			// Unlike find_batch, the buffer has a MINIMUM: `find` is
			// transactional, so a position reporting more matches
			// than fit records no gate and writes no complete answer, and the
			// scan cannot step past it. PATTERN_COUNT is that worst case
			// exactly — one match per pattern at one start.
			hb.WriteString(cSetScannerDecls(s.Find, konst, gateField, scannerType))
			fmt.Fprintf(&cb, `int %[1]s_init(%[2]s *s, const char *input, size_t len, size_t offset) {
    if (!s) return RX_ERR_NULL_ARG;
%[8]s    if (!input) return RX_ERR_NULL_ARG;
    /* The FFI imports are i32. */
    if (len > 0x7FFFFFFF || offset > 0x7FFFFFFF) return RX_ERR_RANGE;
    s->input = input; s->len = len; s->offset = offset; s->done = 0;
%[3]s    return 0;
}

int %[1]s(%[2]s *s, rx_set_match_t *buf, size_t cap) {
    if (!s || !buf) return RX_ERR_NULL_ARG;
    if (cap > 0x7FFFFFFF) return RX_ERR_RANGE;
    /* One match per pattern is the most a position can report, so a buffer that
       holds %[6]s can never overflow — and the same header serves the component
       format, whose scan cannot re-ask a position. One rule for both. */
    if (cap < (size_t)%[6]s) return RX_ERR_RANGE;
%[9]s    if (s->done) return 0;
    int got = ffi_%[1]s(s->input, (int)s->len, (int)s->offset, %[4]s(int *)buf, (int)cap);
    /* Negative is RX_ERR_BT_OVERFLOW, RX_ERR_MALFORMED_CACHE or
       RX_ERR_OUT_OF_ORDER, not a count: a Backtracking member exhausted its
       frame budget, the answer cache's header contradicts itself, or the
       offset went below where that cache was built. Either way what remains is
       UNKNOWN rather
       than nothing, and the code is passed through to the caller. Folding
       either into the "0 means finished" test below would end the scan
       silently and report success. */
    if (got < 0) { s->done = 1; return got; }
    if (got == 0) { s->done = 1; return 0; }
%[7]s    /* The module writes 12-byte {id, start, end} tuples. On wasm32 ptrdiff_t
       is 4 bytes, rx_set_match_t IS that layout, and the answer is already in
       place — the branch below folds away. Anywhere else (a host build for an
       editor or a static check) the structs are wider, so expand in place from
       the LAST element backwards: entry i occupies bytes [i*S, (i+1)*S) with
       S >= 12 while its ints sit at [i*12, i*12+12), so writing downward never
       clobbers a triple not yet read. */
    if (sizeof(rx_set_match_t) != 12) {
        const int *raw = (const int *)buf;
        for (int i = got - 1; i >= 0; i--) {
            int id = raw[i * 3], st = raw[i * 3 + 1], en = raw[i * 3 + 2];
            buf[i].pattern_id = id;
            buf[i].start = (ptrdiff_t)st;
            buf[i].end = (ptrdiff_t)en;
        }
    }
    /* Every tuple in one call shares a start; resume one past it. */
    s->offset = (size_t)buf[0].start + 1;
    return got;
}

void %[1]s_free(%[2]s *s) {
    if (!s) return;
%[5]s}
`, s.Find, scannerType, gateInit, gateArg, cacheFree, konst, blockNotes, ownZero, pendingCheck)
		}
	}
	if hasEmitNameMap(cfg) {
		hb.WriteString("const char *pattern_name(int id);\n\n")
		cb.WriteString(cPatternNameTable(cfg))
	}
	hContent = hb.String()
	cContent = cb.String()
	return
}

// entryGroups is what a `groups_func` entry's pattern yields: the slot count
// and the named-group map. Its zero value means the entry exports no groups.
type entryGroups struct {
	num   int
	named map[string]int
}

// genCPartsForEntrySized generates the .h and .c fragments for one regexp
// entry, with each export's search block. The component generator passes the
// SAME sizes, so the header — the API — stays identical between the two
// formats; its .c half is the module's alone.
//
// It RETURNS the group info it parsed. The component generator needs the same
// numbers for its own .c bodies, and parsing the pattern a second time there
// gave that call an error branch no config could reach — this function has
// already failed on exactly the same pattern by then.
func genCPartsForEntrySized(re config.RegexEntry, importModule string, sizes map[string]compile.SearchSize) (hPart, cPart string, groups entryGroups, err error) {
	var hb, cb strings.Builder

	if re.MatchFunc != "" {
		hb.WriteString(genCMatchHPart(re.MatchFunc))
		cb.WriteString(genCMatchCPart(importModule, re.MatchFunc))
	}
	if re.FindFunc != "" {
		it := cIterTypeName(re.FindFunc)
		h, c := cWithSearch(genCFindHPart(re.FindFunc), genCFindCPart(importModule, re.FindFunc),
			re.FindFunc, it, "_ffi_"+re.FindFunc, sizes[re.FindFunc], false)
		hb.WriteString(h)
		hb.WriteString(cNotesPairDecl(re.FindFunc, it, "iterator", re.FindFunc+"_next"))
		cb.WriteString(c)
		cb.WriteString(cNotesPairDefs(re.FindFunc, it, sizes[re.FindFunc]))
	}
	if re.GroupsFunc != "" {
		exportName := re.GroupsExportName()
		numGroups, namedGroups, e := extractGroupInfo(re.Pattern)
		if e != nil {
			return "", "", entryGroups{}, e
		}
		groups = entryGroups{num: numGroups, named: namedGroups}
		h, c := genCGroupsStubParts(importModule, re.GroupsFunc, exportName, numGroups, namedGroups)
		it := cIterTypeName(re.GroupsFunc)
		h, c = cWithSearch(h, c, re.GroupsFunc, it, "_ffi_"+exportName,
			sizes[re.GroupsFunc], true)
		hb.WriteString(h)
		hb.WriteString(cNotesPairDecl(re.GroupsFunc, it, "iterator", re.GroupsFunc+"_next"))
		cb.WriteString(c)
		cb.WriteString(cNotesPairDefs(re.GroupsFunc, it, sizes[re.GroupsFunc]))
	}
	return hb.String(), cb.String(), groups, nil
}

// genCMatchHPart generates the .h prototype for an anchored-match function.
func genCMatchHPart(funcName string) string {
	return fmt.Sprintf(
		"/* %s: anchored match. Returns end position (>=0), -1 if no match, or\n"+
			"   RX_ERR_BT_OVERFLOW (see above) if the match result is unknown. */\n"+
			"ptrdiff_t %s(const char *input, size_t len);\n\n",
		funcName, funcName)
}

// genCMatchCPart generates the .c FFI declaration and wrapper for an anchored-match function.
func genCMatchCPart(importModule, funcName string) string {
	ffi := "_ffi_" + funcName
	var sb strings.Builder
	fmt.Fprintf(&sb, "__attribute__((import_module(\"%s\"), import_name(\"%s\")))\n", importModule, funcName)
	fmt.Fprintf(&sb, "extern int %s(const unsigned char *ptr, unsigned int len);\n\n", ffi)
	fmt.Fprintf(&sb, "ptrdiff_t %s(const char *input, size_t len) {\n", funcName)
	fmt.Fprintf(&sb, "    return %s((const unsigned char *)input, (unsigned int)len);\n", ffi)
	sb.WriteString("}\n\n")
	return sb.String()
}

// genCFindHPart generates the .h prototype for a non-anchored find function.
func genCFindHPart(funcName string) string {
	iterType := cIterTypeName(funcName)
	return fmt.Sprintf(
		"/* Iterator over %[1]s's non-overlapping matches. CALLER-owned, so two\n"+
			"   scans can be in flight; _free and then _init again restarts one.\n"+
			"   It owns the advance AND the empty-match rule, which the caller used to\n"+
			"   copy out of this comment — the place they got subtly wrong. */\n"+
			"typedef struct {\n"+
			"    const char *input;\n"+
			"    size_t len, offset, prev_end;\n"+
			"    int done;\n"+
			"    /* Opaque. Under wasm_format: component this carries the resource\n"+
			"       handle the scan lives behind; under wasm_format: module it stays\n"+
			"       zero. Never read or write it. */\n"+
			"    unsigned scratch[2];\n"+
			"} %[2]s;\n\n"+
			"/* Starts a scan at offset. Returns 0, or RX_ERR_NULL_ARG. It only WRITES the\n"+
			"   struct, so it may be uninitialised; an iterator already started must be\n"+
			"   passed to %[1]s_free first. */\n"+
			"int %[1]s_init(%[2]s *iter, const char *input, size_t len, size_t offset);\n\n"+
			"/* Writes the next match to *out_match.\n"+
			"     1  a match was written\n"+
			"     0  the scan is finished\n"+
			"     RX_ERR_BT_OVERFLOW  the engine gave up; what remains is UNKNOWN\n"+
			"   The status is the RETURN value, not something written into out_match,\n"+
			"   so 0 stays unambiguously \"finished\". */\n"+
			"int %[1]s_next(%[2]s *iter, rx_match_t *out_match);\n\n"+
			"/* Releases whatever the iterator holds. Under wasm_format: component it drops\n"+
			"   the resource handle the scan lives behind, and is REQUIRED: abandoning an\n"+
			"   iterator strands the input copy and the scan state inside the regexp\n"+
			"   component for the life of the process. Under wasm_format: module it is a\n"+
			"   no-op — the iterator is caller-owned, by value, and holds a borrowed input\n"+
			"   pointer — and is emitted anyway so the SAME source compiles against either\n"+
			"   format.\n\n"+
			"   Call it on every exit path, not just the last one: a break or an early\n"+
			"   return out of the loop leaks under component. Call it before initialising\n"+
			"   the same iterator again, too: _init does not look at what the struct\n"+
			"   held. A second call is a no-op, and so is a call on an iterator that\n"+
			"   finished; a call on a struct that never went through _init is not\n"+
			"   allowed. */\n"+
			"void %[1]s_free(%[2]s *iter);\n\n",
		funcName, iterType)
}

// cIterTypeName is the struct type an iterator uses. It follows the config's
// casing like every other derived symbol; the rx_ prefix and _t suffix are C's
// own convention for a type and inherit from nothing the user chose.
func cIterTypeName(funcName string) string {
	return "rx_" + funcName + "_iter_t"
}

// genCFindCPart generates the .c FFI declaration and wrapper for a non-anchored find function.
func genCFindCPart(importModule, funcName string) string {
	ffi := "_ffi_" + funcName
	iterType := cIterTypeName(funcName)
	var sb strings.Builder
	fmt.Fprintf(&sb, "__attribute__((import_module(\"%s\"), import_name(\"%s\")))\n", importModule, funcName)
	fmt.Fprintf(&sb, "extern long long %s(const unsigned char *ptr, unsigned int len, unsigned int from);\n\n", ffi)

	fmt.Fprintf(&sb, `int %[1]s_init(%[2]s *iter, const char *input, size_t len, size_t offset) {
    if (!iter || !input) return RX_ERR_NULL_ARG;
    iter->input = input;
    iter->len = len;
    iter->offset = offset;
    iter->prev_end = (size_t)-1;
    iter->done = (offset > len);
    /* Cleared so the struct reads the same in both formats. Nothing here uses
       it; the component build keeps its resource handle in it. */
    iter->scratch[0] = 0;
    iter->scratch[1] = 0;
    return 0;
}

/* A no-op for wasm_format: module — the iterator is caller-owned, by value, and
   holds a borrowed input pointer, so there is nothing to give back. It exists
   so the same source compiles against a COMPONENT, where the scan lives behind
   a resource handle that must be dropped. */
void %[1]s_free(%[2]s *iter) {
    if (!iter) return;
    iter->done = 1;
}

int %[1]s_next(%[2]s *iter, rx_match_t *out_match) {
    if (!iter || !out_match) return RX_ERR_NULL_ARG;
    while (!iter->done && iter->offset <= iter->len) {
        /* The WHOLE input plus a start position: offset bounds where the search
           begins, it does not truncate what the engine can see behind it. */
        long long packed = %[3]s((const unsigned char *)iter->input,
                                 (unsigned int)iter->len, (unsigned int)iter->offset);
        if (packed == RX_ERR_BT_OVERFLOW) { iter->done = 1; return RX_ERR_BT_OVERFLOW; }
        if (packed < 0) { iter->done = 1; return 0; }
        size_t start = (size_t)((unsigned long long)packed >> 32);
        size_t end   = (size_t)(packed & 0xFFFFFFFFU);
        /* Advance first, so an empty match cannot spin the scan. */
        iter->offset = (end > start) ? end : start + 1;
        /* Go's FindAllIndex rule: an EMPTY match beginning exactly where the
           previous REPORTED match ended is suppressed. Only whether it is
           reported changes; the advance above is unchanged. */
        if (start == end && iter->prev_end == start) continue;
        iter->prev_end = end;
        out_match->start = (ptrdiff_t)start;
        out_match->end   = (ptrdiff_t)end;
        return 1;
    }
    iter->done = 1;
    return 0;
}

`, funcName, iterType, ffi)
	return sb.String()
}

// toUpperIdent returns s with all lowercase ASCII letters uppercased.
func toUpperIdent(s string) string {
	var b strings.Builder
	for _, c := range s {
		if c >= 'a' && c <= 'z' {
			b.WriteRune(c - 32)
		} else {
			b.WriteRune(c)
		}
	}
	return b.String()
}

// cGroupConst returns the C constant naming a capture group's INDEX.
// e.g. funcName="url_groups", groupName="host" → "url_groups_host".
//
// It used to be a `const char *` holding the NAME, compared by pointer
// identity, with the name also carried in every rx_group_t. That was
// replaced with the index, which is what the caller actually needs to
// address the array, and dropped the per-group name pointer entirely.
//
// The name follows the config's casing rather than C's SCREAMING convention,
// because it derives from a name the user chose (see derivedConstName).
func cGroupConst(funcName, groupName string) string {
	return derivedConstName(funcName, groupName)
}

// genCGroupsStubParts generates the .h and .c fragments for a capture-groups function.
// Both groups_func and named_groups_func entries are handled identically: the generated
// wrapper scans from offset and fills a static rx_group_t array.
// Named groups have their name field pointing to a public char array constant; others are NULL.
// cGroupsNameTable emits the index-aligned capture-group name table and the
// runtime lookup. Entry i names the group at index i and is "" where it has no
// name — index 0 included, the shape regexp.SubexpNames uses.
//
// Format-independent, so both the module and component C stubs call it: the
// name-to-index mapping is part of the API and must not differ between them.
func cGroupsNameTable(funcName string, numGroups int, namedGroups map[string]int) string {
	if len(namedGroups) == 0 {
		return ""
	}
	namesVar := "_" + funcName + "_names"
	groupNameByIdx := make(map[int]string, len(namedGroups))
	for n, idx := range namedGroups {
		groupNameByIdx[idx] = n
	}
	var cb strings.Builder
	fmt.Fprintf(&cb, "static const char *const %s[%d] = {", namesVar, numGroups)
	for i := 0; i < numGroups; i++ {
		if i > 0 {
			cb.WriteString(", ")
		}
		fmt.Fprintf(&cb, "%q", groupNameByIdx[i])
	}
	cb.WriteString("};\n")
	fmt.Fprintf(&cb, "const char *const *%s(void) { return %s; }\n\n",
		derivedFuncName(funcName, "names"), namesVar)

	fmt.Fprintf(&cb, "int %s(const char *name) {\n", derivedFuncName(funcName, "index"))
	cb.WriteString("    if (!name || !name[0]) return -1;\n")
	fmt.Fprintf(&cb, "    for (int i = 0; i < %d; i++) {\n", numGroups)
	fmt.Fprintf(&cb, "        const char *candidate = %s[i];\n", namesVar)
	cb.WriteString("        if (!candidate[0]) continue;\n")
	cb.WriteString("        const char *a = candidate, *b = name;\n")
	cb.WriteString("        while (*a && *a == *b) { a++; b++; }\n")
	cb.WriteString("        if (!*a && !*b) return i;\n")
	cb.WriteString("    }\n    return -1;\n}\n\n")
	return cb.String()
}

func genCGroupsStubParts(importModule, funcName, exportName string, numGroups int, namedGroups map[string]int) (hPart, cPart string) {
	type namedGroup struct {
		name  string
		index int // 1-based capture group index
	}
	var named []namedGroup
	for n, idx := range namedGroups {
		named = append(named, namedGroup{n, idx})
	}
	sort.Slice(named, func(i, j int) bool { return named[i].index < named[j].index })

	funcUpper := toUpperIdent(funcName)
	slotCount := numGroups * 2
	ffi := "_ffi_" + exportName

	var hb, cb strings.Builder

	// .h: group INDEX constants, plus the runtime lookup and the name table.
	// This is what replaced `named_groups_func` — and it gives
	// C named access it never had, since that key was rejected here outright.
	if len(named) > 0 {
		fmt.Fprintf(&hb, "/* Index of each NAMED capture group of %s. Index 0 is the whole\n"+
			"   match; unnamed groups have no constant and are addressed by number. */\n", funcName)
		for _, g := range named {
			fmt.Fprintf(&hb, "#define %s %d\n", cGroupConst(funcName, g.name), g.index)
		}
		hb.WriteString("\n")
	}

	// .h: groups count macro
	fmt.Fprintf(&hb, "#define %s_GROUPS %d\n\n", funcUpper, numGroups)

	if len(named) > 0 {
		fmt.Fprintf(&hb,
			"/* Index of the capture group called `name`, or -1 if this pattern has no\n"+
				"   group of that name. The constants above cover a name known at compile\n"+
				"   time; this is for one chosen at runtime. An EMPTY name is never found:\n"+
				"   a pattern may hold several unnamed groups, so \"\" identifies nothing. */\n"+
				"int %s(const char *name);\n\n", derivedFuncName(funcName, "index"))
		fmt.Fprintf(&hb,
			"/* Capture-group names, ALIGNED WITH INDICES: entry i names the group at\n"+
				"   index i and is \"\" where it has no name, index 0 included. %s_GROUPS\n"+
				"   entries. Same shape as Go's regexp.SubexpNames. */\n"+
				"const char *const *%s(void);\n\n", funcUpper, derivedFuncName(funcName, "names"))
	}

	// .h: the iterator. Single-shot originally, which left the caller
	// hand-rolling the advance and the empty-match guard from a COMMENT — the
	// place they got subtly wrong, and silently. C already had this shape for
	// its set scanner, so this applies a local idiom rather than importing one.
	fmt.Fprintf(&hb,
		"/* Iterator over %[1]s's non-overlapping capture matches. CALLER-owned,\n"+
			"   so two scans can be in flight; _free and then _init again restarts\n"+
			"   one. */\n"+
			"typedef struct {\n"+
			"    const char *input;\n"+
			"    size_t len, offset, prev_end;\n"+
			"    int done;\n"+
			"    /* Opaque — see the find iterator. */\n"+
			"    unsigned scratch[2];\n"+
			"} %[2]s;\n\n"+
			"/* Starts a scan at offset. Returns 0, or RX_ERR_NULL_ARG. Writes only — see\n"+
			"   the find iterator. */\n"+
			"int %[1]s_init(%[2]s *iter, const char *input, size_t len, size_t offset);\n\n"+
			"/* Writes this match's groups into the CALLER'S out_groups[], which must\n"+
			"   hold %[3]s_GROUPS entries. Index 0 is the whole match; a group that\n"+
			"   did not participate is {-1, -1}, so the array length never depends on\n"+
			"   which groups matched. Address a named group with its index constant.\n"+
			"     1  a match was written\n"+
			"     0  the scan is finished\n"+
			"     RX_ERR_BT_OVERFLOW  the engine gave up; what remains is UNKNOWN */\n"+
			"int %[1]s_next(%[2]s *iter, rx_group_t out_groups[static %[3]s_GROUPS]);\n\n"+
			"/* Releases whatever the iterator holds — see the find iterator; under\n"+
			"   wasm_format: component it drops the resource handle and is REQUIRED,\n"+
			"   including before initialising the same iterator again. */\n"+
			"void %[1]s_free(%[2]s *iter);\n\n",
		funcName, cIterTypeName(funcName), funcUpper)

	// .c: the index-aligned name table, plus the lookup. Shared with the
	// component generator: the table and the lookup are format-independent, and
	// two copies would let the name-to-index mapping drift between formats.
	cb.WriteString(cGroupsNameTable(funcName, numGroups, namedGroups))

	// .c: FFI declaration
	fmt.Fprintf(&cb, "__attribute__((import_module(\"%s\"), import_name(\"%s\")))\n", importModule, exportName)
	fmt.Fprintf(&cb, "extern int %s(const unsigned char *ptr, unsigned int len, int *out, unsigned int from);\n\n", ffi)

	// .c: the iterator. The caller-owned array, now driven by a
	// caller-owned iterator too, so nothing here is static and a second scan
	// cannot invalidate the first.
	//
	// NOTE this does NOT make the C stubs thread-safe: the Backtracking engine
	// keeps its stack at a fixed stackBase and its BitState memo at a fixed
	// memoTableBase (compile/engine_backtrack.go). Claim re-entrancy, not
	// thread-safety.
	fmt.Fprintf(&cb, `int %[1]s_init(%[2]s *iter, const char *input, size_t len, size_t offset) {
    if (!iter || !input) return RX_ERR_NULL_ARG;
    iter->input = input;
    iter->len = len;
    iter->offset = offset;
    iter->prev_end = (size_t)-1;
    iter->done = (offset > len);
    iter->scratch[0] = 0;
    iter->scratch[1] = 0;
    return 0;
}

/* A no-op here; under wasm_format: component it drops the resource handle. */
void %[1]s_free(%[2]s *iter) {
    if (!iter) return;
    iter->done = 1;
}

int %[1]s_next(%[2]s *iter, rx_group_t out_groups[static %[5]d]) {
    if (!iter || !out_groups) return RX_ERR_NULL_ARG;
    int slots[%[4]d];
    while (!iter->done && iter->offset <= iter->len) {
        for (int slot_num = 0; slot_num < %[4]d; slot_num++) slots[slot_num] = -1;
        int status = %[3]s((const unsigned char *)iter->input,
                           (unsigned int)iter->len, slots, (unsigned int)iter->offset);
        if (status == RX_ERR_BT_OVERFLOW) { iter->done = 1; return RX_ERR_BT_OVERFLOW; }
        if (status < 0) {
            /* Terminal, not "try the next position": the groups
               export has SCAN-FROM semantics in both wrapper arms, so a
               negative result means there is no match at or after offset. The
               advance-by-one retry this replaced re-scanned the tail once per
               remaining byte. */
            iter->done = 1;
            return 0;
        }
        size_t start = (size_t)slots[0];
        size_t end   = (slots[1] >= 0) ? (size_t)slots[1] : start;
        iter->offset = (end > start) ? end : start + 1;
        /* Go's FindAllSubmatchIndex rule: suppress an EMPTY match beginning
           exactly where the previous reported match ended. */
        if (start == end && iter->prev_end == start) continue;
        iter->prev_end = end;
        for (int group_num = 0; group_num < %[5]d; group_num++) {
            if (slots[group_num * 2] >= 0) {
                out_groups[group_num].start = (ptrdiff_t)slots[group_num * 2];
                out_groups[group_num].end   = (ptrdiff_t)slots[group_num * 2 + 1];
            } else {
                out_groups[group_num].start = -1;
                out_groups[group_num].end   = -1;
            }
        }
        return 1;
    }
    iter->done = 1;
    return 0;
}

`, funcName, cIterTypeName(funcName), ffi, slotCount, numGroups)

	return hb.String(), cb.String()
}

