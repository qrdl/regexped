// cSetScannerDecls is the `find` scanner: its doc comment, its caller-owned
// struct, and the init / step / free triple.
//
// `<func>_free` is emitted in BOTH formats. Here it frees the answer cache an
// overlapping set's scanner owns when the header was built with RX_SET_CACHE on,
// and does nothing otherwise — the struct then holds only a borrowed input
// pointer and the gate array inline. Under `wasm_format: component` the scan's
// state lives inside the regexp component behind a handle that has to be
// dropped. A caller must be able to switch formats without editing code, so the
// call exists in both.
func cSetScannerDecls(find, konst, gateField, scannerType string) string {
	return fmt.Sprintf(`/* Caller-owned scanner for %[1]s. Two scans may be in flight at once, and
   _free followed by _init restarts a scan.

   NOT COPYABLE once initialised. For an overlapping set the scanner OWNS a
   heap region, so a copy plus two _free calls frees it twice; and the
   descriptor it builds holds a pointer INTO itself, so a copy left behind by a
   move would drive the original's gate array. Declare it where it lives, pass
   its ADDRESS, and let _free end it.

   The scanner holds the INPUT as well as the position: the
   input never changes during a scan while the position changes every step, so
   the old split — remembering the position and taking the input on every
   step — was backwards, and let a caller pass a DIFFERENT buffer on a later
   step with the stored position silently indexing into it.

   %[1]s fills your array with every match at the FIRST position at or after
   the scanner's offset — they all share that start — and returns HOW MANY.
   0 means the scan is finished. cap must be at least %[2]s — one match per
   pattern, the most a single position can report — and a smaller cap is
   RX_ERR_RANGE, with nothing written and the scan not advanced.

       rx_set_match_t buf[%[2]s];
       %[4]s sc;
       if (%[1]s_init(&sc, input, len, 0) != 0) { ... }
       for (int n; (n = %[1]s(&sc, buf, %[2]s)) > 0; )
           for (int i = 0; i < n; i++) { ... buf[i] ... }
       %[1]s_free(&sc);

   That last call frees an overlapping scanner's answer cache, and is REQUIRED
   for wasm_format: component. */
typedef struct {
    const char *input;
    size_t len, offset;
    int done;
%[3]s} %[4]s;

/* 0 on success, a negative RX_ERR_* otherwise. An EMPTY input is legitimate
   (a*, (?:), x?, \\A\\z all match it) and offset > len is not an error either
   — the ABI defines it as "nothing found". It only WRITES the struct, so it may
   be uninitialised; a scanner already started must be passed to _free first. */
int %[1]s_init(%[4]s *s, const char *input, size_t len, size_t offset);
int %[1]s(%[4]s *s, rx_set_match_t *buf, size_t cap);

/* The answer cache, in YOUR memory: for a build with no allocator
   (-DRX_SET_CACHE=0), or one that wants to place the cache itself.

   %[1]s_cache_bytes says how many bytes the cache needs for an input of len.
   0 means the scan needs none from you: the set has no answer cache, the
   input is too long for one, or the build is wasm_format: component, whose
   regexp component keeps its own. %[1]s_set_cache hands a buffer of at least
   that many bytes to a scanner; call it after _init and before the first
   %[1]s. Without a cache an overlapping scan that keeps long matches alive
   costs time quadratic in the input; the answers are the same either way.

       size_t need = %[1]s_cache_bytes(len);
       %[1]s_init(&sc, input, len, 0);
       if (need && need <= sizeof mem) %[1]s_set_cache(&sc, mem, sizeof mem);

   0 on success, and when no buffer is needed (buf is then not used).
   RX_ERR_RANGE when bytes is below what this input needs, RX_ERR_NULL_ARG for
   a null scanner or a null buf that is needed; on an error the scanner is
   unchanged and keeps whatever cache _init gave it. A cache _init allocated
   itself is freed here and replaced by yours.

   The buffer must outlive the scan and serve ONE scanner at a time; _free
   never frees it, and _init forgets it, so a restarted scan hands it over
   again. Any alignment works. */
size_t %[1]s_cache_bytes(size_t len);
int %[1]s_set_cache(%[4]s *s, void *buf, size_t bytes);

%[5]s
/* Releases whatever the scanner holds. Call it: with RX_SET_CACHE on, an
   overlapping set's scanner OWNS a heap region and abandoning one leaks it.
   Without the cache it is a no-op — the scanner is caller-owned, by value, and
   holds a borrowed input pointer and the gate array inline.

   Call it before initialising the same scanner again: _init does not look at
   what the struct held, so a scanner that owns a cache and is initialised
   again without _free leaks it. A second _free is a no-op; a _free on a struct
   that never went through _init is not allowed.

   It exists so that the same source compiles against either output kind. Under
   wasm_format: component the scan's state lives inside the regexp component
   and a handle must be dropped, so the call is mandatory there; calling it here
   costs nothing and lets you switch formats without editing code.

   Safe to call more than once, and on a scanner that finished. */
void %[1]s_free(%[4]s *s);

`, find, konst, gateField, scannerType, strings.TrimSuffix(cNotesPairDecl(find, scannerType, "scanner", find), "\n"))
}

// cPatternNameTable is the `emit_name_map: true` helper. Shared with the
// component stub: it maps ids to names and has nothing to do with the output
// kind.
func cPatternNameTable(cfg config.BuildConfig) string {
	var b strings.Builder
	b.WriteString("static const char *rx_pattern_names[] = {")
	for i, re := range cfg.Regexps {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", re.Name)
	}
	b.WriteString("};\nconst char *pattern_name(int id) { int n=sizeof(rx_pattern_names)/sizeof(*rx_pattern_names); return (id>=0&&id<n)?rx_pattern_names[id]:\"\"; }\n")
	return b.String()
}

// cCachePart is the C cache plan's answer-cache arithmetic: k and bytes for an
// input of m positions — the bare header when the set has no cache, only a
// program sweep.
func cCachePart(sh compile.OverlapCacheShape, consts overlapCacheConsts) string {
	if !sh.Eligible {
		return fmt.Sprintf("    unsigned long long k = 1;\n    unsigned long long bytes = %dULL;\n", consts.Hdr)
	}
	return fmt.Sprintf(`    unsigned long long row = %[5]dULL;
    unsigned long long cell = %[6]dULL;
    unsigned long long k = m;
    if (%[3]dULL + cell + 4 + m * row > %[4]dULL) {
        k = (unsigned long long)rx_sqrt_((double)m * %[1]d * 4 / (double)row);
        if (k < 16) k = 16;
        if (k > m) k = m;
    }
    unsigned long long nb = (m + k - 1) / k;
    unsigned long long bytes = %[3]dULL + nb * cell + 4 + k * row;
`, consts.Cells, sh.Patterns, consts.Hdr, consts.Max, consts.Row, consts.Cell)
}

// cSweepPart adds a program sweep's part to the C cache plan's bytes: after the
// cache's, 8-aligned, checkpointed by the same formula over its own geometry,
// when it fits the budget. "" for a set with none.
func cSweepPart(sh compile.OverlapCacheShape, consts overlapCacheConsts) string {
	if sh.SweepCells == 0 {
		return ""
	}
	return fmt.Sprintf(`    {
        unsigned long long srow = %[3]dULL, scell = %[4]dULL, sk = m;
        if (%[1]dULL + scell + 4 + m * srow > %[2]dULL) {
            sk = (unsigned long long)rx_sqrt_((double)m * %[5]d * 4 / (double)srow);
            if (sk < 16) sk = 16;
            if (sk > m) sk = m;
        }
        unsigned long long sb = %[1]dULL + (m + sk - 1) / sk * scell + 4 + sk * srow;
        if (sb <= %[2]dULL) bytes = ((bytes + 7) & ~7ULL) + sb;
    }
`, consts.Hdr, consts.Max, sh.SweepRow, sh.SweepCells*4+4, sh.SweepCells)
}

