// asStub generates an AssemblyScript stub file for all regexp entries in cfg.
// out is the full output path or "-" for stdout.
func asStub(cfg config.BuildConfig, out string) error {
	content, err := genASStubFile(cfg)
	if err != nil {
		return fmt.Errorf("generate AS stub: %w", err)
	}
	if content == "" {
		return nil
	}
	// See jsStub: the namespace applies on the stdout path too.
	content = applyNamespace(cfg, "as", content)
	if out == "-" {
		_, err := fmt.Print(content)
		return err
	}
	return writeStub(out, []byte(content))
}

// genASStubFile generates the content of an AssemblyScript stub file.
func genASStubFile(cfg config.BuildConfig) (string, error) {
	var parts []string
	for _, re := range cfg.Regexps {
		part, err := genASStubsForEntry(re, cfg.ImportModule)
		if err != nil {
			return "", err
		}
		if part != "" {
			parts = append(parts, part)
		}
	}
	setSection := genASSetSection(cfg)
	if len(parts) == 0 && setSection == "" {
		return "", nil
	}

	var sb strings.Builder
	sb.WriteString("// Auto-generated by regexped. Do not edit.\n\n")
	sb.WriteString(asSentinelPreamble())
	sb.WriteString(strings.Join(parts, ""))
	sb.WriteString(setSection)
	return sb.String(), nil
}

// asSentinelPreamble emits the two sentinels every AssemblyScript export
// reports failure with.
//
// AS uses SENTINELS, not exceptions, and this is measured rather than assumed.
// asc 0.28.13 rejects `try { } catch { }` outright — "ERROR AS100: Not
// implemented: Exceptions" — and a `throw` compiles to a call to the imported
// `abort`, a one-way trap the AS caller cannot handle. So a throw here would be
// strictly worse than a sentinel: uncatchable rather than merely awkward.
func asSentinelPreamble() string {
	return `/** The Backtracking engine exhausted its frame budget: the result is UNKNOWN,
 *  NOT "no match". Returned by the scalar and i64-returning exports. */
export const RX_ERR_BT_OVERFLOW: i32 = -2;

/** The same condition from an export whose return is a POINTER, where 0
 *  already means "finished" and there is no negative value to spend. */
export const RX_ITER_ERROR: u32 = 0xFFFFFFFF;

`
}

// genASSetSection generates AssemblyScript set wrappers.
func genASSetSection(cfg config.BuildConfig) string {
	if !hasSetExports(cfg) {
		return ""
	}
	var out strings.Builder
	out.WriteString("\n// ---- set composition wrappers ----\n\n")
	// EXPORTED. A caller iterating a set's find gets SetMatch values back, so a
	// module-private class left them with no way to name the type
	//. It is also in the namespace-rewritten shared-symbol
	// list, which only makes sense for a symbol the caller can see.
	out.WriteString("export class SetMatch { constructor(public patternId: i32, public start: u32, public end: u32) {} }\n")
	for _, s := range cfg.Sets {
		n := patternsInSet(s, cfg)
		konst := screamingCase(s.Name) + "_PATTERN_COUNT"
		idN := idSpaceSize(s, cfg)
		idKonst := screamingCase(s.Name) + "_ID_SPACE"
		wide := wideAllForm(s, cfg)

		fmt.Fprintf(&out, "// Number of patterns in set %q. Sizes the match buffer: the iterator can\n// receive at most this many matches at one position.\nexport const %s: i32 = %d;\n\n", s.Name, konst, n)
		fmt.Fprintf(&out, "// One past the largest pattern id set %q can report. Pattern ids are global\n// indices into regexps:, so a set holding a few late-declared patterns has a\n// small count and a large id space. Everything indexed BY an id \u2014 the gate\n// array, the _all bitmask \u2014 is sized from this.\nexport const %s: i32 = %d;\n\n", s.Name, idKonst, idN)

		decl := func(name, sig string) {
			fmt.Fprintf(&out, "@external(%q, %q)\ndeclare function ffi_%s%s;\n\n", cfg.ImportModule, name, name, sig)
		}
		// Parameter lists come from the ONE descriptor in set_stub.go; only
		// the AssemblyScript spelling of each is decided here (R12).
		setCaps := setCapabilities(s, cfg)
		sig := func(kind string) string {
			capability := capByKind(setCaps, kind)
			if capability == nil {
				panic("generate: AS stub asked for the signature of an undeclared capability " + kind)
			}
			return "(" + capability.render(asABIParam, ", ") + "): " + asABIRet(capability.Ret)
		}
		if s.MatchAny != "" {
			decl(s.MatchAny, sig("match_any"))
			fmt.Fprintf(&out, `/** Id of SOME pattern matching the whole input, or -1.
 *  Which id you get is unspecified when several patterns match.
 *
 *  May also return RX_ERR_BT_OVERFLOW (-2): a Backtracking member of this set
 *  exhausted its frame budget, so the answer is UNKNOWN rather than -1. Test
 *  for it before reading a negative result as "no match" — the doc here used
 *  to promise only -1 while the sentinel came straight through
 */
export function %s(input: ArrayBuffer): i32 {
    return ffi_%s(changetype<usize>(input), input.byteLength);
}
`, s.MatchAny, s.MatchAny)
		}
		if s.MatchAll != "" {
			if wide {
				decl(s.MatchAll, sig("match_all"))
				fmt.Fprintf(&out, `/** Ids of every pattern matching the whole input. */
export function %s(input: ArrayBuffer): Array<i32> | null {
    const bits = new StaticArray<u8>((%s + 7) >> 3);
    const n = ffi_%s(changetype<usize>(input), input.byteLength, changetype<usize>(bits));
    // The wide form returns a count, so the sentinel is distinguishable:
    // overflow means the bitmap was never answered, not that it is empty.
    // NULL rather than a throw: asc cannot CATCH, so a throw here would be an
    // uncatchable abort. Array is a reference type, so null is legal.
    if (n == %d) return null;
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if (bits[k >> 3] & (1 << (k & 7))) out.push(k);
    return out;
}
`, s.MatchAll, idKonst, s.MatchAll, btOverflow, idKonst)
			} else {
				decl(s.MatchAll, sig("match_all"))
				fmt.Fprintf(&out, `/** Ids of every pattern matching the whole input. */
export function %s(input: ArrayBuffer): Array<i32> | null {
    const raw = ffi_%s(changetype<usize>(input), input.byteLength);
    // NO overflow sentinel here: the narrow form's return IS the bitmask, so
    // every 64-bit value is a legal answer. -2 means ids 1..63 matched and id
    // 0 did not, which a sentinel test would report as an engine failure. The
    // real sentinel cannot reach this form — a Backtracking member forces the
    // wide one.
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if ((raw >> i64(k)) & 1) out.push(k);
    return out;
}
`, s.MatchAll, s.MatchAll, idKonst)
			}
		}
		if s.ScanAny != "" {
			decl(s.ScanAny, sig("scan_any"))
			fmt.Fprintf(&out, `/** One pattern id matching somewhere at or after `+"`offset`"+`, or -1.
 *  Which id you get is unspecified when several patterns match; no position
 *  is reported. */
export function %s(input: ArrayBuffer, offset: u32): i32 {
    const r = ffi_%s(changetype<usize>(input), input.byteLength, i32(offset));
    // Returned, not thrown: asc cannot CATCH (try/catch is
    // "ERROR AS100: Not implemented: Exceptions") and a throw calls the
    // imported abort — a trap the caller has no recourse against. Test the
    // sentinel EXACTLY: -1 is a real answer and folding the two reports
    // "unknown" as a confident "no".
    return r;
}
`, s.ScanAny, s.ScanAny)
		}
		if s.ScanAll != "" {
			if wide {
				decl(s.ScanAll, sig("scan_all"))
				fmt.Fprintf(&out, `/** Ids of every pattern matching somewhere at or after `+"`offset`"+`. */
export function %s(input: ArrayBuffer, offset: u32): Array<i32> | null {
    const bits = new StaticArray<u8>((%s + 7) >> 3);
    const n = ffi_%s(changetype<usize>(input), input.byteLength, i32(offset), changetype<usize>(bits));
    // The wide form returns a count, so the sentinel is distinguishable:
    // overflow means the bitmap was never answered, not that it is empty.
    // NULL rather than a throw: asc cannot CATCH, so a throw here would be an
    // uncatchable abort. Array is a reference type, so null is legal.
    if (n == %d) return null;
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if (bits[k >> 3] & (1 << (k & 7))) out.push(k);
    return out;
}
`, s.ScanAll, idKonst, s.ScanAll, btOverflow, idKonst)
			} else {
				decl(s.ScanAll, sig("scan_all"))
				fmt.Fprintf(&out, `/** Ids of every pattern matching somewhere at or after `+"`offset`"+`. */
export function %s(input: ArrayBuffer, offset: u32): Array<i32> | null {
    const raw = ffi_%s(changetype<usize>(input), input.byteLength, i32(offset));
    // NO overflow sentinel here: the narrow form's return IS the bitmask, so
    // every 64-bit value is a legal answer. -2 means ids 1..63 matched and id
    // 0 did not, which a sentinel test would report as an engine failure. The
    // real sentinel cannot reach this form — a Backtracking member forces the
    // wide one.
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if ((raw >> i64(k)) & 1) out.push(k);
    return out;
}
`, s.ScanAll, s.ScanAll, idKonst)
			}
		}
		if s.Find != "" {
			iterName := config.PascalCaseForValidation(s.Find) + "Iter"
			// EVERY set with `find` takes the gate array, overlapping included
			// — the branch that omitted it was unreachable
			// and is gone.
			decl(s.Find, sig("find"))
			gateField := "    gates: StaticArray<u32>;\n"
			gateInit := "        this.gates = new StaticArray<u32>(" + idKonst + ");\n"
			gateArg := "changetype<usize>(this.gates), "
			// AssemblyScript has no generators, so `find` is an explicit
			// iterator object — caller-owned, so two scans can be in flight
			// and re-creating it restarts the scan.
			fmt.Fprintf(&out, `/** Iterator over the set's matches. next() returns null when exhausted
 *  OR when the engine gave up; err() after the loop tells them apart. asc
 *  cannot catch an exception, so the failure is recorded, not thrown. */
export class %[1]s {
    private input: ArrayBuffer;
    private from: i32;
    private done: bool = false;
    private overflowed: bool = false;
    private n: i32 = 0;
    private i: i32 = 0;
    private buf: StaticArray<i32>;
%[2]s    constructor(input: ArrayBuffer, offset: u32) {
        this.input = input;
        this.from = i32(offset);
        this.buf = new StaticArray<i32>(%[3]s * 3);
%[4]s    }
    next(): SetMatch | null {
        while (true) {
            if (this.i < this.n) {
                const o = this.i * 3;
                this.i++;
                return new SetMatch(this.buf[o], u32(this.buf[o + 1]), u32(this.buf[o + 2]));
            }
            if (this.done) return null;
            const got = ffi_%[5]s(changetype<usize>(this.input), this.input.byteLength, this.from,
                %[6]schangetype<usize>(this.buf), %[3]s);
            // Before the "no more matches" test: the sentinel means the engine
            // gave up, so ending the iteration here would report a finished
            // scan when the rest of the input was never answered. It is
            // RECORDED rather than thrown — asc cannot catch — and read back
            // with err() after the loop.
            if (got == %[7]d) { this.done = true; this.overflowed = true; return null; }
            if (got <= 0) { this.done = true; return null; }
            this.n = got;
            this.i = 0;
            // Every tuple in one call shares a start; resume one past it.
            this.from = this.buf[1] + 1;
        }
    }
    /** RX_ERR_BT_OVERFLOW if the scan stopped because the engine gave up and
     *  what remained was UNKNOWN, 0 if it ran to completion. Check it after
     *  the loop: an unchecked err() means a silently truncated match list. */
    err(): i32 {
        return this.overflowed ? RX_ERR_BT_OVERFLOW : 0;
    }
}

/** Starts a scan at `+"`offset`"+`. Each next() call returns one match. */
export function %[5]s(input: ArrayBuffer, offset: u32): %[1]s {
    return new %[1]s(input, offset);
}
`, iterName, gateField, konst, gateInit, s.Find, gateArg, btOverflow, btOverflowMsg(s.Find))
		}
		out.WriteString("\n")
	}
	if hasEmitNameMap(cfg) {
		names := make([]string, len(cfg.Regexps))
		for i, re := range cfg.Regexps {
			names[i] = fmt.Sprintf("%q", re.Name)
		}
		fmt.Fprintf(&out, "const _patternNames: string[] = [%s];\n", strings.Join(names, ", "))
		out.WriteString("export function patternName(id: i32): string { return id >= 0 && id < _patternNames.length ? _patternNames[id] : ''; }\n")
	}
	return out.String()
}

// genASStubsForEntry generates the AS stub content for a single regexp entry.
func genASStubsForEntry(re config.RegexEntry, importModule string) (string, error) {
	var out string
	written := false

	if re.MatchFunc != "" {
		out += genASMatchStub(importModule, re.MatchFunc)
		written = true
	}
	if re.FindFunc != "" {
		out += genASFindStub(importModule, re.FindFunc)
		written = true
	}
	if re.GroupsFunc != "" {
		numGroups, namedGroups, err := extractGroupInfo(re.Pattern)
		if err != nil {
			return "", err
		}
		exportName := re.GroupsExportName()
		out += genASGroupsStub(importModule, re.GroupsFunc, exportName, numGroups)
		out += genASGroupIndexConsts(re.GroupsFunc, numGroups, namedGroups)
		written = true
	}

	if !written {
		return "", nil
	}
	return out, nil
}

// genASMatchStub generates an anchored-match AS stub.
// Returns end position (≥0) or -1 if no match — mirrors Go and C API.
func genASMatchStub(importModule, funcName string) string {
	ffi := "_ffi_" + funcName
	var sb strings.Builder
	fmt.Fprintf(&sb, "@external(\"%s\", \"%s\")\n", importModule, funcName)
	fmt.Fprintf(&sb, "declare function %s(ptr: usize, len: usize): i32;\n\n", ffi)
	fmt.Fprintf(&sb, "/** Returns end position (>=0), -1 if no match, or RX_ERR_BT_OVERFLOW\n")
	fmt.Fprintf(&sb, " *  if the Backtracking engine exhausted its frame budget and the answer\n")
	fmt.Fprintf(&sb, " *  is UNKNOWN. Test that sentinel EXACTLY: -1 is a real answer, and\n")
	fmt.Fprintf(&sb, " *  folding the two reports \"unknown\" as a confident \"no\". */\n")
	fmt.Fprintf(&sb, "export function %s(input: ArrayBuffer): i32 {\n", funcName)
	fmt.Fprintf(&sb, "  return %s(changetype<usize>(input), <usize>input.byteLength);\n", ffi)
	sb.WriteString("}\n\n")
	return sb.String()
}

// genASFindStub generates a stateless find AS stub.
// The caller passes an offset and receives packed (absStart<<32|absEnd) or -1.
func genASFindStub(importModule, funcName string) string {
	ffi := "_ffi_" + funcName
	var sb strings.Builder
	fmt.Fprintf(&sb, "@external(\"%s\", \"%s\")\n", importModule, funcName)
	fmt.Fprintf(&sb, "declare function %s(ptr: usize, len: usize, from: usize): i64;\n\n", ffi)
	// An ITERATOR, not a single shot. It was the latter, which left the caller
	// hand-rolling the advance and the empty-match rule out of this comment.
	// Sentinel-based, so nothing is allocated per match: AS nullability is
	// reference-types only, so an object-returning next() would allocate.
	fmt.Fprintf(&sb, `/** Iterator over %[1]s's non-overlapping matches. next() returns the
 *  packed (absStart << 32 | absEnd), -1 when the scan is finished, or
 *  RX_ERR_BT_OVERFLOW when the engine gave up and what remains is UNKNOWN.
 *  Unpack with: const start = i32(<u64>packed >> 32), end = i32(<u32>packed); */
export class %[2]s {
  private input: ArrayBuffer;
  private offset: u32;
  private prevEnd: i64 = -1;
  private done: bool = false;
  constructor(input: ArrayBuffer, offset: u32) {
    this.input = input;
    this.offset = offset;
  }
  next(): i64 {
    const len = this.input.byteLength;
    while (!this.done && this.offset <= u32(len)) {
      // Whole buffer plus a start position: offset bounds where the search
      // begins, it does not truncate what the engine sees behind it, so the
      // returned positions are already absolute.
      const packed = %[3]s(changetype<usize>(this.input), <usize>len, <usize>this.offset);
      if (packed == %[4]d) { this.done = true; return %[4]d; }
      if (packed < 0) { this.done = true; return -1; }
      const start = i64(<u64>packed >> 32);
      const end = i64(<u32>packed);
      // Advance first, so an empty match cannot spin the scan.
      this.offset = u32(end > start ? end : start + 1);
      // Go's FindAllIndex rule: an EMPTY match beginning exactly where the
      // previous REPORTED match ended is suppressed.
      if (start == end && this.prevEnd == start) continue;
      this.prevEnd = end;
      return packed;
    }
    this.done = true;
    return -1;
  }
}

/** Starts a scan at offset. */
export function %[1]s(input: ArrayBuffer, offset: u32): %[2]s {
  return new %[2]s(input, offset);
}

`, funcName, asIterTypeName(funcName), ffi, btOverflow)
	return sb.String()
}

// genASGroupsStub generates a stateless capture-groups AS stub.
// Returns the dataStart pointer of a static Int32Array slots buffer, or 0 on no match.
// Slot layout: [g0_start, g0_end, g1_start, g1_end, ...] as i32 values (absolute offsets).
func genASGroupsStub(importModule, funcName, exportName string, numGroups int) string {
	ffi := "_ffi_" + exportName
	slotCount := numGroups * 2

	var sb strings.Builder
	fmt.Fprintf(&sb, "@external(\"%s\", \"%s\")\n", importModule, exportName)
	fmt.Fprintf(&sb, "declare function %s(ptr: usize, len: usize, out_ptr: usize, from: usize): i32;\n\n", ffi)
	// An ITERATOR, not a single shot, and the slot buffer moved INTO it. The
	// module-level buffer this replaces was not re-entrant: two interleaved
	// scans clobbered each other, and the returned pointer was silently
	// invalidated by the next call.
	//
	// Sentinel-based, so nothing is allocated per match: AS nullability is
	// reference-types only, so an object-returning next() would allocate.
	fmt.Fprintf(&sb, `/** Iterator over %[1]s's non-overlapping capture matches. next() returns a
 *  pointer to THIS iterator's slot buffer, 0 when the scan is finished, or
 *  RX_ITER_ERROR when the engine gave up and what remains is UNKNOWN.
 *
 *  The pointer is valid only until the next next() call — the buffer is
 *  reused. Slot layout: [g0_start, g0_end, g1_start, g1_end, ...] as i32,
 *  absolute offsets; group 0 is the whole match, and a group that did not
 *  participate has start = -1. Address a named group with its index constant
 *  and %[1]s_capture. */
export class %[2]s {
  private input: ArrayBuffer;
  private offset: u32;
  private prevEnd: i32 = -1;
  private done: bool = false;
  private slots: Int32Array = new Int32Array(%[4]d);
  constructor(input: ArrayBuffer, offset: u32) {
    this.input = input;
    this.offset = offset;
  }
  next(): u32 {
    const len = this.input.byteLength;
    while (!this.done && this.offset <= u32(len)) {
      this.slots.fill(-1);
      // Whole buffer plus a start position; slots come back absolute.
      const status = %[3]s(
        changetype<usize>(this.input),
        <usize>len,
        this.slots.dataStart,
        <usize>this.offset,
      );
      if (status == %[5]d) { this.done = true; return RX_ITER_ERROR; }
      if (status < 0) {
        // Terminal, not "try the next position": the groups
        // export has SCAN-FROM semantics in both wrapper arms, so a negative
        // result means there is no match at or after offset. The
        // advance-by-one retry this replaced re-scanned the tail once per
        // remaining byte.
        this.done = true;
        return 0;
      }
      const start = this.slots[0];
      const end = this.slots[1] >= 0 ? this.slots[1] : start;
      this.offset = u32(end > start ? end : start + 1);
      // Go's FindAllSubmatchIndex rule: suppress an EMPTY match beginning
      // exactly where the previous reported match ended.
      if (start == end && this.prevEnd == start) continue;
      this.prevEnd = end;
      return u32(this.slots.dataStart);
    }
    this.done = true;
    return 0;
  }
}

/** Starts a scan at offset. */
export function %[1]s(input: ArrayBuffer, offset: u32): %[2]s {
  return new %[2]s(input, offset);
}

`, funcName, asIterTypeName(funcName), ffi, slotCount, btOverflow)

	// <FUNC>_GROUPS and <func>_capture: captures are addressed by arithmetic —
	// load<i32>(slots + 8*g) twice and hand-roll a UTF-8 decode. These make
	// bounds-checking and looping over all groups possible at all. Named
	// groups reach the same slots through the index constants
	// genASGroupIndexConsts emits; AS used to have no named
	// access at all, because `named_groups_func` was rejected here.
	//
	// _capture takes `input` again ON PURPOSE: the slots are offsets, so
	// decoding needs the buffer. A stub that remembered the last input would
	// be exactly the mutable-static pattern C decision (8) removes, and would
	// break the moment two scans interleave. The raw offsets stay reachable,
	// so this is additive.
	fmt.Fprintf(&sb, "export const %s_GROUPS: i32 = %d;\n\n", toUpperIdent(funcName), numGroups)
	fmt.Fprintf(&sb, "/** Decoded text of capture group g (0 = whole match) from a slots pointer\n"+
		" *  returned by %s, or null when the group did not participate OR g is out\n"+
		" *  of range. Those are different errors and this return does not\n"+
		" *  distinguish them: an empty capture is legal, so the empty string cannot\n"+
		" *  separate them either, and %s_GROUPS lets a caller bound-check without\n"+
		" *  calling. */\n", funcName, toUpperIdent(funcName))
	fmt.Fprintf(&sb, "export function %s_capture(input: ArrayBuffer, slots: u32, g: i32): string | null {\n", funcName)
	fmt.Fprintf(&sb, "  if (slots == 0 || g < 0 || g >= %s_GROUPS) return null;\n", toUpperIdent(funcName))
	sb.WriteString("  const s = load<i32>(usize(slots) + usize(8 * g));\n")
	sb.WriteString("  const e = load<i32>(usize(slots) + usize(8 * g + 4));\n")
	sb.WriteString("  if (s < 0 || e < s) return null;\n")
	sb.WriteString("  return String.UTF8.decode(input.slice(s, e));\n")
	sb.WriteString("}\n\n")
	return sb.String()
}

// asABIParam spells one set-ABI parameter in AssemblyScript. set_stub.go's
// descriptor decides WHICH parameters a capability takes and in what order;
// this decides only how each is written.
func asABIParam(p abiParam) string {
	switch p {
	case abiInputPtr:
		return "ptr: usize"
	case abiInputLen:
		return "len: i32"
	case abiFrom:
		return "from: i32"
	case abiGatePtr:
		return "gates: usize"
	case abiBitmapPtr, abiTuplePtr:
		return "out: usize"
	case abiOutCap:
		return "cap: i32"
	case abiCursor:
		return "cursor: i64"
	}
	panic("generate: unknown abiParam")
}

func asABIRet(r abiRet) string {
	if r == abiRetI64 {
		return "i64"
	}
	return "i32"
}

// genASGroupIndexConsts emits name→index addressing for a groups function.
// Replaces the retired `named_groups_func`, which AS rejected
// outright — so this is named access AssemblyScript never had.
//
// Flat constants rather than JS/TS's single frozen object: AS has no
// `as const`, and its object support is heavier than a handful of i32s. Names
// follow the config's casing, not AS's.
func genASGroupIndexConsts(funcName string, numGroups int, namedGroups map[string]int) string {
	if len(namedGroups) == 0 {
		return ""
	}
	names := groupNameSlots(numGroups, namedGroups)

	var sb strings.Builder
	fmt.Fprintf(&sb, "/** Index of each NAMED capture group of %s, for use with %s_capture\n"+
		" *  and with the slot arithmetic. Index 0 is the whole match; unnamed groups\n"+
		" *  have no constant and are addressed by number. */\n", funcName, funcName)
	for idx, name := range names {
		if name == "" {
			continue
		}
		fmt.Fprintf(&sb, "export const %s: i32 = %d;\n", derivedConstName(funcName, name), idx)
	}
	sb.WriteString("\n")

	indexFn := derivedFuncName(funcName, "index")
	fmt.Fprintf(&sb, "/** Index of the capture group called `name`, or -1 if this pattern has no\n"+
		" *  group of that name. The constants above cover a name known at compile\n"+
		" *  time; this is for one chosen at runtime. An EMPTY name is never found:\n"+
		" *  a pattern may hold several unnamed groups, so \"\" identifies nothing. */\n"+
		"export function %s(name: string): i32 {\n", indexFn)
	for idx, name := range names {
		if name == "" {
			continue
		}
		fmt.Fprintf(&sb, "  if (name == %q) return %d;\n", name, idx)
	}
	sb.WriteString("  return -1;\n}\n\n")

	namesFn := derivedFuncName(funcName, "names")
	fmt.Fprintf(&sb, "/** Capture-group names ALIGNED WITH INDICES: entry i names the group at\n"+
		" *  index i and is \"\" where it has no name, index 0 included. */\n"+
		"export function %s(): string[] {\n  return [", namesFn)
	for i, name := range names {
		if i > 0 {
			sb.WriteString(", ")
		}
		fmt.Fprintf(&sb, "%q", name)
	}
	sb.WriteString("];\n}\n\n")
	return sb.String()
}

// asIterTypeName is the class an AS iterator uses. It follows the config's
// casing like every other derived symbol; the Iter suffix is the only part
// this generator chooses.
func asIterTypeName(funcName string) string {
	return derivedFuncName(funcName, "iter")
}
