// asStub generates an AssemblyScript stub file for all regexp entries in cfg.
// out is the full output path or "-" for stdout.
func asStub(cfg config.BuildConfig, out string) error {
	content, err := genASStubFile(cfg)
	if err != nil {
		return fmt.Errorf("generate AS stub: %w", err)
	}
	if content == "" {
		return nil
	}
	if out == "-" {
		_, err := fmt.Print(content)
		return err
	}
	return writeStub(out, []byte(content))
}

// genASStubFile generates the content of an AssemblyScript stub file.
func genASStubFile(cfg config.BuildConfig) (string, error) {
	var parts []string
	for _, re := range cfg.Regexps {
		part, err := genASStubsForEntry(re, cfg.ImportModule)
		if err != nil {
			return "", err
		}
		if part != "" {
			parts = append(parts, part)
		}
	}
	setSection := genASSetSection(cfg)
	if len(parts) == 0 && setSection == "" {
		return "", nil
	}

	var sb strings.Builder
	sb.WriteString("// Auto-generated by regexped. Do not edit.\n\n")
	sb.WriteString(strings.Join(parts, ""))
	sb.WriteString(setSection)
	return sb.String(), nil
}

// genASSetSection generates AssemblyScript set wrappers.
func genASSetSection(cfg config.BuildConfig) string {
	if !hasSetExports(cfg) {
		return ""
	}
	var out strings.Builder
	out.WriteString("\n// ---- set composition wrappers ----\n\n")
	out.WriteString("class SetMatch { constructor(public patternId: i32, public start: u32, public end: u32) {} }\n")
	for _, s := range cfg.Sets {
		n := patternsInSet(s, cfg)
		konst := screamingCase(s.Name) + "_PATTERN_COUNT"
		idN := idSpaceSize(s, cfg)
		idKonst := screamingCase(s.Name) + "_ID_SPACE"
		wide := wideAllForm(s, cfg)

		fmt.Fprintf(&out, "// Number of patterns in set %q. Sizes the match buffer: the iterator can\n// receive at most this many matches at one position.\nexport const %s: i32 = %d;\n\n", s.Name, konst, n)
		fmt.Fprintf(&out, "// One past the largest pattern id set %q can report. Pattern ids are global\n// indices into regexps:, so a set holding a few late-declared patterns has a\n// small count and a large id space. Everything indexed BY an id \u2014 the gate\n// array, the _all bitmask \u2014 is sized from this.\nexport const %s: i32 = %d;\n\n", s.Name, idKonst, idN)


		decl := func(name, sig string) {
			fmt.Fprintf(&out, "@external(%q, %q)\ndeclare function ffi_%s%s;\n\n", cfg.ImportModule, name, name, sig)
		}
		if s.MatchAny != "" {
			decl(s.MatchAny, "(ptr: usize, len: i32): i32")
			fmt.Fprintf(&out, `/** Id of SOME pattern matching the whole input, or -1. */
export function %s(input: ArrayBuffer): i32 {
    return ffi_%s(changetype<usize>(input), input.byteLength);
}
`, s.MatchAny, s.MatchAny)
		}
		if s.MatchAll != "" {
			if wide {
				decl(s.MatchAll, "(ptr: usize, len: i32, out: usize): i32")
				fmt.Fprintf(&out, `/** Ids of every pattern matching the whole input. */
export function %s(input: ArrayBuffer): Array<i32> {
    const bits = new StaticArray<u8>((%s + 7) >> 3);
    ffi_%s(changetype<usize>(input), input.byteLength, changetype<usize>(bits));
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if (bits[k >> 3] & (1 << (k & 7))) out.push(k);
    return out;
}
`, s.MatchAll, idKonst, s.MatchAll, idKonst)
			} else {
				decl(s.MatchAll, "(ptr: usize, len: i32): i64")
				fmt.Fprintf(&out, `/** Ids of every pattern matching the whole input. */
export function %s(input: ArrayBuffer): Array<i32> {
    const mask = ffi_%s(changetype<usize>(input), input.byteLength);
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if ((mask >> i64(k)) & 1) out.push(k);
    return out;
}
`, s.MatchAll, s.MatchAll, idKonst)
			}
		}
		if s.ScanAny != "" {
			decl(s.ScanAny, "(ptr: usize, len: i32, from: i32): i32")
			fmt.Fprintf(&out, `/** One pattern id matching somewhere at or after `+"`offset`"+`, or -1.
 *  Which id you get is unspecified when several patterns match; no position
 *  is reported. */
export function %s(input: ArrayBuffer, offset: u32): i32 {
    return ffi_%s(changetype<usize>(input), input.byteLength, i32(offset));
}
`, s.ScanAny, s.ScanAny)
		}
		if s.ScanAll != "" {
			if wide {
				decl(s.ScanAll, "(ptr: usize, len: i32, from: i32, out: usize): i32")
				fmt.Fprintf(&out, `/** Ids of every pattern matching somewhere at or after `+"`offset`"+`. */
export function %s(input: ArrayBuffer, offset: u32): Array<i32> {
    const bits = new StaticArray<u8>((%s + 7) >> 3);
    ffi_%s(changetype<usize>(input), input.byteLength, i32(offset), changetype<usize>(bits));
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if (bits[k >> 3] & (1 << (k & 7))) out.push(k);
    return out;
}
`, s.ScanAll, idKonst, s.ScanAll, idKonst)
			} else {
				decl(s.ScanAll, "(ptr: usize, len: i32, from: i32): i64")
				fmt.Fprintf(&out, `/** Ids of every pattern matching somewhere at or after `+"`offset`"+`. */
export function %s(input: ArrayBuffer, offset: u32): Array<i32> {
    const mask = ffi_%s(changetype<usize>(input), input.byteLength, i32(offset));
    const out = new Array<i32>();
    for (let k = 0; k < %s; k++) if ((mask >> i64(k)) & 1) out.push(k);
    return out;
}
`, s.ScanAll, s.ScanAll, idKonst)
			}
		}
		if s.Find != "" {
			iterName := config.PascalCaseForValidation(s.Find) + "Iter"
			gateField, gateInit, gateArg := "", "", ""
			if gatedFind(s) {
				decl(s.Find, "(ptr: usize, len: i32, from: i32, gates: usize, out: usize, cap: i32): i32")
				gateField = "    gates: StaticArray<u32>;\n"
				gateInit = "        this.gates = new StaticArray<u32>(" + idKonst + ");\n"
				gateArg = "changetype<usize>(this.gates), "
			} else {
				decl(s.Find, "(ptr: usize, len: i32, from: i32, out: usize, cap: i32): i32")
			}
			// AssemblyScript has no generators, so `find` is an explicit
			// iterator object — caller-owned, so two scans can be in flight
			// and re-creating it restarts the scan.
			fmt.Fprintf(&out, `/** Iterator over the set's matches. next() returns null when exhausted. */
export class %[1]s {
    private input: ArrayBuffer;
    private from: i32;
    private done: bool = false;
    private n: i32 = 0;
    private i: i32 = 0;
    private buf: StaticArray<i32>;
%[2]s    constructor(input: ArrayBuffer, offset: u32) {
        this.input = input;
        this.from = i32(offset);
        this.buf = new StaticArray<i32>(%[3]s * 3);
%[4]s    }
    next(): SetMatch | null {
        while (true) {
            if (this.i < this.n) {
                const o = this.i * 3;
                this.i++;
                return new SetMatch(this.buf[o], u32(this.buf[o + 1]), u32(this.buf[o + 2]));
            }
            if (this.done) return null;
            const got = ffi_%[5]s(changetype<usize>(this.input), this.input.byteLength, this.from,
                %[6]schangetype<usize>(this.buf), %[3]s);
            if (got <= 0) { this.done = true; return null; }
            this.n = got;
            this.i = 0;
            // Every tuple in one call shares a start; resume one past it.
            this.from = this.buf[1] + 1;
        }
    }
}

/** Starts a scan at `+"`offset`"+`. Each next() call returns one match. */
export function %[5]s(input: ArrayBuffer, offset: u32): %[1]s {
    return new %[1]s(input, offset);
}
`, iterName, gateField, konst, gateInit, s.Find, gateArg)
		}
		out.WriteString("\n")
	}
	if hasEmitNameMap(cfg) {
		names := make([]string, len(cfg.Regexps))
		for i, re := range cfg.Regexps {
			names[i] = fmt.Sprintf("%q", re.Name)
		}
		fmt.Fprintf(&out, "const _patternNames: string[] = [%s];\n", strings.Join(names, ", "))
		out.WriteString("export function patternName(id: i32): string { return id >= 0 && id < _patternNames.length ? _patternNames[id] : ''; }\n")
	}
	return out.String()
}

// genASStubsForEntry generates the AS stub content for a single regexp entry.
func genASStubsForEntry(re config.RegexEntry, importModule string) (string, error) {
	if re.NamedGroupsFunc != "" {
		return "", fmt.Errorf("named_groups_func is not supported for AS stubs; use groups_func instead")
	}

	var out string
	written := false

	if re.MatchFunc != "" {
		out += genASMatchStub(importModule, re.MatchFunc)
		written = true
	}
	if re.FindFunc != "" {
		out += genASFindStub(importModule, re.FindFunc)
		written = true
	}
	if re.GroupsFunc != "" {
		numGroups, _, err := extractGroupInfo(re.Pattern)
		if err != nil {
			return "", err
		}
		exportName := re.GroupsExportName()
		out += genASGroupsStub(importModule, re.GroupsFunc, exportName, numGroups)
		written = true
	}

	if !written {
		return "", nil
	}
	return out, nil
}

// genASMatchStub generates an anchored-match AS stub.
// Returns end position (≥0) or -1 if no match — mirrors Go and C API.
func genASMatchStub(importModule, funcName string) string {
	ffi := "_ffi_" + funcName
	var sb strings.Builder
	fmt.Fprintf(&sb, "@external(\"%s\", \"%s\")\n", importModule, funcName)
	fmt.Fprintf(&sb, "declare function %s(ptr: usize, len: usize): i32;\n\n", ffi)
	fmt.Fprintf(&sb, "/** Returns end position (≥0) or -1 if no match.\n")
	fmt.Fprintf(&sb, " *  Throws if the Backtracking engine exhausted its frame budget: the\n")
	fmt.Fprintf(&sb, " *  match result is unknown, so -1 (a definite \"no\") would be wrong. */\n")
	fmt.Fprintf(&sb, "export function %s(input: ArrayBuffer): i32 {\n", funcName)
	fmt.Fprintf(&sb, "  const r = %s(changetype<usize>(input), <usize>input.byteLength);\n", ffi)
	fmt.Fprintf(&sb, "  if (r == %d) throw new Error(\"%s\");\n", btOverflow, btOverflowMsg(funcName))
	sb.WriteString("  return r;\n")
	sb.WriteString("}\n\n")
	return sb.String()
}

// genASFindStub generates a stateless find AS stub.
// The caller passes an offset and receives packed (absStart<<32|absEnd) or -1.
func genASFindStub(importModule, funcName string) string {
	ffi := "_ffi_" + funcName
	var sb strings.Builder
	fmt.Fprintf(&sb, "@external(\"%s\", \"%s\")\n", importModule, funcName)
	fmt.Fprintf(&sb, "declare function %s(ptr: usize, len: usize): i64;\n\n", ffi)
	fmt.Fprintf(&sb, "/** Finds match starting from offset.\n")
	fmt.Fprintf(&sb, " *  Returns packed (absStart << 32 | absEnd) as i64, or -1 if not found.\n")
	fmt.Fprintf(&sb, " *  To iterate non-overlapping matches, advance past each match; a pattern\n")
	fmt.Fprintf(&sb, " *  that can match empty needs the guard, or offset never moves:\n")
	fmt.Fprintf(&sb, " *    const s = i32(<u64>r >> 32), e = i32(<u32>r);\n")
	fmt.Fprintf(&sb, " *    offset = e > s ? e : s + 1; */\n")
	fmt.Fprintf(&sb, "export function %s(input: ArrayBuffer, offset: u32): i64 {\n", funcName)
	sb.WriteString("  const len = input.byteLength;\n")
	sb.WriteString("  if (offset > u32(len)) return -1;\n")
	fmt.Fprintf(&sb, "  const r = %s(changetype<usize>(input) + <usize>offset, <usize>(len - offset));\n", ffi)
	fmt.Fprintf(&sb, "  if (r == %d) throw new Error(\"%s\");\n", btOverflow, btOverflowMsg(funcName))
	sb.WriteString("  if (r < 0) return -1;\n")
	sb.WriteString("  const relStart = i32(<u64>r >> 32);\n")
	sb.WriteString("  const relEnd   = i32(<u32>r);\n")
	sb.WriteString("  return (i64(i32(offset) + relStart) << 32) | i64(i32(offset) + relEnd);\n")
	sb.WriteString("}\n\n")
	return sb.String()
}

// genASGroupsStub generates a stateless capture-groups AS stub.
// Returns the dataStart pointer of a static Int32Array slots buffer, or 0 on no match.
// Slot layout: [g0_start, g0_end, g1_start, g1_end, ...] as i32 values (absolute offsets).
func genASGroupsStub(importModule, funcName, exportName string, numGroups int) string {
	ffi := "_ffi_" + exportName
	slotsVar := "_" + funcName + "_slots"
	slotCount := numGroups * 2

	var sb strings.Builder
	fmt.Fprintf(&sb, "@external(\"%s\", \"%s\")\n", importModule, exportName)
	fmt.Fprintf(&sb, "declare function %s(ptr: usize, len: usize, out_ptr: usize): i32;\n\n", ffi)
	fmt.Fprintf(&sb, "const %s = new Int32Array(%d);\n\n", slotsVar, slotCount)
	fmt.Fprintf(&sb, "/** Finds capture match starting from offset.\n")
	fmt.Fprintf(&sb, " *  Returns dataStart pointer to slots buffer (pairs: start,end per group), or 0 on no match.\n")
	fmt.Fprintf(&sb, " *  Group 0 is the full match. Unmatched optional groups have start=-1, end=-1.\n")
	fmt.Fprintf(&sb, " *  Slot layout: [g0_start, g0_end, g1_start, g1_end, ...] as i32 values.\n")
	fmt.Fprintf(&sb, " *  To iterate non-overlapping matches, advance past each match; a pattern\n")
	fmt.Fprintf(&sb, " *  that can match empty needs the guard, or offset never moves:\n")
	fmt.Fprintf(&sb, " *    offset = slots[1] > slots[0] ? slots[1] : slots[0] + 1; */\n")
	fmt.Fprintf(&sb, "export function %s(input: ArrayBuffer, offset: u32): u32 {\n", funcName)
	sb.WriteString("  const len = input.byteLength;\n")
	sb.WriteString("  if (offset > u32(len)) return 0;\n")
	fmt.Fprintf(&sb, "  %s.fill(-1);\n", slotsVar)
	fmt.Fprintf(&sb, "  const r = %s(\n", ffi)
	sb.WriteString("    changetype<usize>(input) + <usize>offset,\n")
	sb.WriteString("    <usize>(len - offset),\n")
	fmt.Fprintf(&sb, "    %s.dataStart,\n", slotsVar)
	sb.WriteString("  );\n")
	fmt.Fprintf(&sb, "  if (r == %d) throw new Error(\"%s\");\n", btOverflow, btOverflowMsg(funcName))
	sb.WriteString("  if (r < 0) return 0;\n")
	fmt.Fprintf(&sb, "  for (let i = 0; i < %d; i++) {\n", slotCount)
	fmt.Fprintf(&sb, "    if (%s[i] >= 0) %s[i] += i32(offset);\n", slotsVar, slotsVar)
	sb.WriteString("  }\n")
	fmt.Fprintf(&sb, "  return u32(%s.dataStart);\n", slotsVar)
	sb.WriteString("}\n\n")

	// <FUNC>_GROUPS and <func>_capture: AS has no named groups (the generator
	// errors if named_groups_func is set), so captures are addressed purely by
	// arithmetic — load<i32>(slots + 8*g) twice and hand-roll a UTF-8 decode.
	// These make bounds-checking and looping over all groups possible at all.
	//
	// _capture takes `input` again ON PURPOSE: the slots are offsets, so
	// decoding needs the buffer. A stub that remembered the last input would
	// be exactly the mutable-static pattern C decision (8) removes, and would
	// break the moment two scans interleave. The raw offsets stay reachable,
	// so this is additive.
	fmt.Fprintf(&sb, "export const %s_GROUPS: i32 = %d;\n\n", toUpperIdent(funcName), numGroups)
	fmt.Fprintf(&sb, "/** Decoded text of capture group g (0 = whole match) from a slots pointer\n"+
		" *  returned by %s, or null when the group did not participate OR g is out\n"+
		" *  of range. Those are different errors and this return does not\n"+
		" *  distinguish them: an empty capture is legal, so the empty string cannot\n"+
		" *  separate them either, and %s_GROUPS lets a caller bound-check without\n"+
		" *  calling. */\n", funcName, toUpperIdent(funcName))
	fmt.Fprintf(&sb, "export function %s_capture(input: ArrayBuffer, slots: u32, g: i32): string | null {\n", funcName)
	fmt.Fprintf(&sb, "  if (slots == 0 || g < 0 || g >= %s_GROUPS) return null;\n", toUpperIdent(funcName))
	sb.WriteString("  const s = load<i32>(usize(slots) + usize(8 * g));\n")
	sb.WriteString("  const e = load<i32>(usize(slots) + usize(8 * g + 4));\n")
	sb.WriteString("  if (s < 0 || e < s) return null;\n")
	sb.WriteString("  return String.UTF8.decode(input.slice(s, e));\n")
	sb.WriteString("}\n\n")
	return sb.String()
}
