// rustStub generates a Rust stub file for all regexp entries and sets in cfg.
// out is the full output path or "-" for stdout.
func rustStub(cfg config.BuildConfig, out string) error {
	singleInner, err := genRustStubsInner(cfg.Regexps, cfg.ImportModule)
	if err != nil {
		return fmt.Errorf("generate Rust stub: %w", err)
	}
	setInner := genRustSetInner(cfg)
	allInner := singleInner + setInner
	if allInner == "" {
		return nil
	}
	combined := "// Auto-generated by regexped. Do not edit.\n\n" + wrapRustModule(allInner, cfg.ImportModule)
	if out == "-" {
		_, err := os.Stdout.WriteString(combined)
		return err
	}
	return writeStub(out, []byte(combined))
}

// genRustSetInner generates Rust wrappers for all sets in cfg.
// Returns unindented content for placement INSIDE
// pub mod <importModule>.
//
// D15: `find` is iterator-only and yields individual SetMatch values; the
// iterator owns the reusable tuple buffer and, for a gated set, the gate
// array, so gates never appear in the public surface. D16: every buffer is
// declared in terms of the emitted <SET>_PATTERN_COUNT constant.
func genRustSetInner(cfg config.BuildConfig) string {
	if !hasSetExports(cfg) {
		return ""
	}
	var out strings.Builder
	out.WriteString("/// A match reported by a set `find` iterator.\n" +
		`#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SetMatch {
    /// Pattern ids are i32: the FFI import already returns one, so this
    /// removes a cast rather than adding one. start/end stay usize because
    /// they index a slice.
    pub pattern_id: i32,
    pub start: usize,
    pub end: usize,
}

impl SetMatch {
    /// Returns the matched byte range as a Rust Range.
    pub fn range(self) -> std::ops::Range<usize> { self.start..self.end }
}

`)
	for _, s := range cfg.Sets {
		n := patternsInSet(s, cfg)
		konst := screamingCase(s.Name) + "_PATTERN_COUNT"
		idN := idSpaceSize(s, cfg)
		idKonst := screamingCase(s.Name) + "_ID_SPACE"
		wide := wideAllForm(s, cfg)

		fmt.Fprintf(&out, "/// Number of patterns in set %q. Sizes the match buffer: `find` can\n/// report at most this many matches at one position.\npub const %s: usize = %d;\n\n", s.Name, konst, n)
		fmt.Fprintf(&out, "/// One past the largest pattern id set %q can report. Pattern ids are\n/// global indices into `regexps:`, so a set holding a few late-declared\n/// patterns has a small count and a large id space. Everything indexed BY an\n/// id — the gate array, the `_all` bitmask — is sized from this.\npub const %s: usize = %d;\n\n", s.Name, idKonst, idN)

		fmt.Fprintf(&out, "#[link(wasm_import_module = %q)]\nunsafe extern \"C\" {\n", cfg.ImportModule)
		decl := func(name, sig string) {
			fmt.Fprintf(&out, "    #[link_name = %q]\n    fn ffi_%s%s;\n", name, name, sig)
		}
		if s.MatchAny != "" {
			decl(s.MatchAny, "(ptr: *const u8, len: i32) -> i32")
		}
		if s.MatchAll != "" {
			if wide {
				decl(s.MatchAll, "(ptr: *const u8, len: i32, out: *mut u8) -> i32")
			} else {
				decl(s.MatchAll, "(ptr: *const u8, len: i32) -> i64")
			}
		}
		if s.ScanAny != "" {
			decl(s.ScanAny, "(ptr: *const u8, len: i32, from: i32) -> i32")
		}
		if s.ScanAll != "" {
			if wide {
				decl(s.ScanAll, "(ptr: *const u8, len: i32, from: i32, out: *mut u8) -> i32")
			} else {
				decl(s.ScanAll, "(ptr: *const u8, len: i32, from: i32) -> i64")
			}
		}
		if s.Find != "" {
			if gatedFind(s) {
				decl(s.Find, "(ptr: *const u8, len: i32, from: i32, gates: *mut u32, out: *mut i32, cap: i32) -> i32")
			} else {
				decl(s.Find, "(ptr: *const u8, len: i32, from: i32, out: *mut i32, cap: i32) -> i32")
			}
		}
		out.WriteString("}\n\n")

		if s.MatchAny != "" {
			fmt.Fprintf(&out, `/// Returns the id of SOME pattern matching the whole input, or None.
/// A set is unordered, so which id you get is unspecified when several match.
pub fn %s(input: &[u8]) -> Option<i32> {
    let r = unsafe { ffi_%s(input.as_ptr(), input.len() as i32) };
    if r < 0 { None } else { Some(r) }
}

`, s.MatchAny, s.MatchAny)
		}
		if s.MatchAll != "" {
			fmt.Fprintf(&out, "/// Yields the id of every pattern matching the whole input.\n"+
				"///\n"+
				"/// An iterator rather than a `Vec`: the ABI hands back a bitmap whose set\n"+
				"/// bits can be yielded lazily with nothing materialised, so a caller who\n"+
				"/// stops early allocates nothing. `.collect()` gives you a Vec.\n"+
				"pub fn %s(input: &[u8]) -> impl Iterator<Item = i32> + '_ {\n", s.MatchAll)
			if wide {
				fmt.Fprintf(&out, `    let mut bits = [0u8; (%s + 7) / 8];
    unsafe { ffi_%s(input.as_ptr(), input.len() as i32, bits.as_mut_ptr()) };
    (0..%s as i32).filter(move |k| bits[(*k / 8) as usize] & (1u8 << (*k %% 8)) != 0)
}

`, idKonst, s.MatchAll, idKonst)
			} else {
				fmt.Fprintf(&out, `    let mask = unsafe { ffi_%s(input.as_ptr(), input.len() as i32) } as u64;
    (0..%s as i32).filter(move |k| mask & (1u64 << k) != 0)
}

`, s.MatchAll, idKonst)
			}
		}
		if s.ScanAny != "" {
			fmt.Fprintf(&out, "/// Returns one pattern id that matches somewhere at or after `from`, or\n"+
				"/// None. Which id you get is unspecified when several patterns match; it\n"+
				"/// names a genuinely matching pattern, and no position is reported.\n"+
				`pub fn %s(input: &[u8], offset: usize) -> Option<i32> {
    let r = unsafe { ffi_%s(input.as_ptr(), input.len() as i32, offset as i32) };
    if r < 0 { return None; }
    Some(r)
}

`, s.ScanAny, s.ScanAny)
		}
		if s.ScanAll != "" {
			fmt.Fprintf(&out, "/// Yields the id of every pattern matching somewhere at or after `offset`.\n"+
				"/// See match_all for why this is an iterator.\n"+
				"pub fn %s(input: &[u8], offset: usize) -> impl Iterator<Item = i32> + '_ {\n", s.ScanAll)
			if wide {
				fmt.Fprintf(&out, `    let mut bits = [0u8; (%s + 7) / 8];
    unsafe { ffi_%s(input.as_ptr(), input.len() as i32, offset as i32, bits.as_mut_ptr()) };
    (0..%s as i32).filter(move |k| bits[(*k / 8) as usize] & (1u8 << (*k %% 8)) != 0)
}

`, idKonst, s.ScanAll, idKonst)
			} else {
				fmt.Fprintf(&out, `    let mask = unsafe { ffi_%s(input.as_ptr(), input.len() as i32, offset as i32) } as u64;
    (0..%s as i32).filter(move |k| mask & (1u64 << k) != 0)
}

`, s.ScanAll, idKonst)
			}
		}
		if s.Find != "" {
			iterName := iterTypeName(s.Find)
			gateSlots := 0
			if gatedFind(s) {
				gateSlots = idN
			}
			// A set big enough to make the iterator a heavy VALUE holds its
			// arrays behind a Box instead; small sets keep the inline arrays
			// and the zero-allocation scan. Both shapes deref to a slice, so
			// only the declarations and the initialisers differ.
			boxed := boxSetBuffers(n, gateSlots)
			bufField := "    buf: [[i32; 3]; " + konst + "],\n"
			bufInit := " buf: [[0; 3]; " + konst + "],"
			allocDoc := ""
			if boxed {
				bufField = "    buf: Box<[[i32; 3]]>,\n"
				bufInit = " buf: vec![[0; 3]; " + konst + "].into_boxed_slice(),"
				allocDoc = "///\n/// This set is large enough that the buffer would be a heavy value to\n/// move, so it is heap-allocated once when the iterator is created. Small\n/// sets keep it inline and allocate nothing.\n"
			}
			gateField, gateInit, gateArg, gateDoc := "", "", "", ""
			if gatedFind(s) {
				gateField = "    gates: [u32; " + idKonst + "],\n"
				gateInit = " gates: [0u32; " + idKonst + "],"
				if boxed {
					gateField = "    gates: Box<[u32]>,\n"
					gateInit = " gates: vec![0u32; " + idKonst + "].into_boxed_slice(),"
				}
				gateArg = "self.gates.as_mut_ptr(), "
				gateDoc = " and a zeroed gate array"
			}
			fmt.Fprintf(&out, `/// Iterator over the set's matches. It owns a reusable tuple buffer%s,
/// refills at each matching position and yields that position's matches one
/// at a time before advancing. Dropping and re-creating it restarts the scan.
%spub struct %s<'a> {
    input: &'a [u8],
    from: i32,
    done: bool,
%s%s    count: i32,
    idx: i32,
}

impl<'a> Iterator for %s<'a> {
    type Item = SetMatch;
    fn next(&mut self) -> Option<SetMatch> {
        loop {
            if self.idx < self.count {
                let e = self.buf[self.idx as usize];
                self.idx += 1;
                return Some(SetMatch { pattern_id: e[0], start: e[1] as usize, end: e[2] as usize });
            }
            if self.done { return None; }
            let n = unsafe {
                ffi_%s(self.input.as_ptr(), self.input.len() as i32, self.from,
                    %sself.buf.as_mut_ptr() as *mut i32, %s as i32)
            };
            if n <= 0 { self.done = true; return None; }
            // The buffer is sized at the set's pattern count, the exact worst
            // case for a single position, so n can never exceed it.
            self.count = n;
            self.idx = 0;
            // Every tuple in one call shares a start; resume one past it.
            self.from = self.buf[0][1] + 1;
        }
    }
}

`, gateDoc, allocDoc, iterName, gateField, bufField, iterName, s.Find, gateArg, konst)
			fmt.Fprintf(&out, "/// Starts a scan at `offset`. Each step yields one match.\n"+
				`pub fn %s(input: &[u8], offset: usize) -> %s<'_> {
    %s { input, from: offset as i32, done: false,%s%s count: 0, idx: 0 }
}

`, s.Find, iterName, iterName, gateInit, bufInit)
		}
	}
	if hasEmitNameMap(cfg) {
		out.WriteString("pub fn pattern_name(id: i32) -> &'static str {\n    match id {\n")
		for i, re := range cfg.Regexps {
			fmt.Fprintf(&out, "        %d => %q,\n", i, re.Name)
		}
		out.WriteString("        _ => \"\",\n    }\n}\n\n")
	}
	return out.String()
}

// genRustStubsInner generates the unindented inner content for single-pattern stubs
// (without the pub mod wrapper). Returns "" when there is nothing to emit.
func genRustStubsInner(entries []config.RegexEntry, importModule string) (string, error) {
	var bodyParts []string
	for _, re := range entries {
		body, err := genRustStubsForEntry(re, importModule)
		if err != nil {
			return "", err
		}
		if body != "" {
			bodyParts = append(bodyParts, body)
		}
	}
	if len(bodyParts) == 0 {
		return "", nil
	}
	return strings.TrimRight(strings.Join(bodyParts, ""), "\n") + "\n", nil
}

// wrapRustModule wraps inner (unindented) content in pub mod <moduleName> { }.
// Each non-empty line is indented by 4 spaces.
func wrapRustModule(inner, moduleName string) string {
	var out strings.Builder
	fmt.Fprintf(&out, "pub mod %s {\n", moduleName)
	for _, line := range strings.Split(strings.TrimRight(inner, "\n"), "\n") {
		if line == "" {
			out.WriteString("\n")
		} else {
			fmt.Fprintf(&out, "    %s\n", line)
		}
	}
	out.WriteString("}\n")
	return out.String()
}

// genRustStubFile is kept for backward compatibility with tests.
func genRustStubFile(entries []config.RegexEntry, importModule string) (string, error) {
	inner, err := genRustStubsInner(entries, importModule)
	if err != nil || inner == "" {
		return "", err
	}
	return "// Auto-generated by regexped. Do not edit.\n\n" + wrapRustModule(inner, importModule), nil
}

// genRustStubsForEntry generates the Rust stub content for a single entry.
func genRustStubsForEntry(re config.RegexEntry, importModule string) (string, error) {
	var out string
	written := false

	if re.MatchFunc != "" {
		out += genRustMatchStub(importModule, re.MatchFunc)
		written = true
	}
	if re.FindFunc != "" {
		out += genRustFindIterStub(importModule, re.FindFunc)
		written = true
	}
	if re.GroupsFunc != "" || re.NamedGroupsFunc != "" {
		numGroups, namedGroups, err := extractGroupInfo(re.Pattern)
		if err != nil {
			return "", err
		}
		exportName := re.GroupsExportName()
		if re.GroupsFunc != "" {
			out += genRustGroupsIterStub(importModule, re.GroupsFunc, exportName, true, numGroups)
			written = true
		}
		if re.NamedGroupsFunc != "" {
			declareFFI := re.GroupsFunc == ""
			out += genRustNamedGroupsIterStub(importModule, re.NamedGroupsFunc, exportName, declareFFI, numGroups, namedGroups)
			written = true
		}
	}

	if !written {
		return "", nil
	}
	return out, nil
}

// iterTypeName derives a unique Rust type name for an iterator from the function name.
// "find_github_token" → "FindGithubTokenIter"
func iterTypeName(funcName string) string {
	var b strings.Builder
	upper := true
	for _, c := range funcName {
		if c == '_' {
			upper = true
			continue
		}
		if upper {
			if c >= 'a' && c <= 'z' {
				c -= 'a' - 'A'
			}
			upper = false
		}
		b.WriteRune(c)
	}
	b.WriteString("Iter")
	return b.String()
}

// genRustMatchStub generates an anchored-match stub.
// The WASM export is named funcName; the internal FFI binding uses the ffi_ prefix
// to avoid a name collision with the public Rust wrapper.
func genRustMatchStub(importModule, funcName string) string {
	ffiName := "ffi_" + funcName
	return fmt.Sprintf(`#[link(wasm_import_module = "%s")]
unsafe extern "C" {
    #[link_name = "%s"]
    fn %s(ptr: *const u8, len: usize) -> i32;
}

/// Returns the end position of the match (exclusive), or None if no match.
/// The match is anchored: it starts at the beginning of input.
///
/// # Panics
/// Panics if the pattern compiled to the Backtracking engine and the input
/// exhausted its frame budget: the engine cannot tell whether the input
/// matches, so None (a definite "no") would be a lie.
pub fn %s(input: &[u8]) -> Option<usize> {
    match unsafe { %s(input.as_ptr(), input.len()) } {
        n if n >= 0 => Some(n as usize),
        %d => panic!("%s"),
        _ => None,
    }
}

`, importModule, funcName, ffiName, funcName, ffiName, btOverflow, btOverflowMsg(funcName))
}

// genRustFindIterStub generates a find iterator.
// The WASM export is named funcName; ffi_ prefix avoids collision with the
// public constructor of the same name.
func genRustFindIterStub(importModule, funcName string) string {
	ffiName := "ffi_" + funcName
	iterName := iterTypeName(funcName)
	return fmt.Sprintf(`#[link(wasm_import_module = "%s")]
unsafe extern "C" {
    #[link_name = "%s"]
    fn %s(ptr: *const u8, len: usize, from: usize) -> i64;
}

pub struct %s<'a> {
    input: &'a [u8],
    offset: usize,
    /// End of the last REPORTED match, for Go's adjacent-empty rule.
    prev_end: Option<usize>,
}

impl<'a> Iterator for %s<'a> {
    type Item = (usize, usize);

    fn next(&mut self) -> Option<(usize, usize)> {
        if self.offset > self.input.len() {
            return None;
        }
        // The WHOLE input plus a start position: offset bounds where the
        // search begins, it does not truncate what the engine can see behind
        // it. Positions come back absolute.
        match unsafe { %s(self.input.as_ptr(), self.input.len(), self.offset) } {
            %d => panic!("%s"),
            -1 => None,
            n  => {
                let abs_start = (n as u64 >> 32) as usize;
                let abs_end   = (n as u32) as usize;
                let (start, end) = (abs_start - self.offset, abs_end - self.offset);
                self.offset += if end > start { end } else { start + 1 };
                // Go's FindAllIndex rule: an EMPTY match beginning exactly
                // where the previous match ended is suppressed. The advance
                // above is unchanged — it still steps past a zero-length
                // match, which is what stops the loop spinning; only whether
                // the match is REPORTED changes.
                if abs_start == abs_end && self.prev_end == Some(abs_start) {
                    return self.next();
                }
                self.prev_end = Some(abs_end);
                Some((abs_start, abs_end))
            }
        }
    }
}

/// Returns an iterator over all non-overlapping matches at or after offset.
/// Each item is an absolute (start, end) byte range.
/// Use .next() to get only the first match.
///
/// The whole input is passed on every call and offset only bounds where the
/// search STARTS, so a leading \b, \B, ^ or (?m:^) is judged against the
/// real preceding byte rather than a slice edge.
///
/// # Panics
/// next() panics if the pattern compiled to the Backtracking engine and the
/// input exhausted its frame budget: the engine cannot tell whether the input
/// matches, so ending iteration would be a lie.
pub fn %s(input: &[u8], offset: usize) -> %s<'_> {
    %s { input, offset, prev_end: None }
}

`, importModule, funcName, ffiName, iterName, iterName, ffiName, btOverflow, btOverflowMsg(funcName), funcName, iterName, iterName)
}

// genRustGroupsIterStub generates a capture-groups iterator.
// exportName is the actual WASM export (= funcName unless named_groups_func
// shares the same WASM export, in which case exportName = groups_func value).
// declareFFI controls whether the extern "C" block is emitted; pass false when
// a sibling named-groups stub in the same file already declared it.
func genRustGroupsIterStub(importModule, funcName, exportName string, declareFFI bool, numGroups int) string {
	ffiName := "ffi_" + exportName
	slotCount := numGroups * 2

	var ffiDecl string
	if declareFFI {
		ffiDecl = fmt.Sprintf(`#[link(wasm_import_module = "%s")]
unsafe extern "C" {
    #[link_name = "%s"]
    fn %s(ptr: *const u8, len: usize, out: *mut i32) -> i32;
}

`, importModule, exportName, ffiName)
	}

	iterName := iterTypeName(funcName)
	return ffiDecl + fmt.Sprintf(`pub struct %s<'a> {
    input: &'a [u8],
    offset: usize,
    /// End of the last REPORTED match, for Go's adjacent-empty rule.
    prev_end: Option<usize>,
}

impl<'a> Iterator for %s<'a> {
    type Item = Vec<Option<(usize, usize)>>;

    fn next(&mut self) -> Option<Vec<Option<(usize, usize)>>> {
        loop {
            if self.offset > self.input.len() {
                return None;
            }
            let mut slots = [-1i32; %d];
            let r = unsafe { %s(self.input.as_ptr(), self.input.len(), slots.as_mut_ptr(), self.offset) };
            if r == %d {
                panic!("%s");
            }
            if r < 0 {
                if self.offset == self.input.len() {
                    return None;
                }
                self.offset += 1;
                continue;
            }
            // Slots are ABSOLUTE: the whole input is passed on every call.
            let abs_start = slots[0] as usize;
            let abs_end = if slots[1] >= 0 { slots[1] as usize } else { abs_start };
            self.offset = if abs_end > abs_start { abs_end } else { abs_start + 1 };
            let mut result = Vec::with_capacity(%d);
            for i in 0..%d {
                let start = slots[i * 2];
                let end   = slots[i * 2 + 1];
                result.push(if start < 0 { None } else { Some((start as usize, end as usize)) });
            }
            return Some(result);
        }
    }
}

/// Returns an iterator over all non-overlapping capture matches in input.
/// Group positions are absolute byte offsets. Index 0 is the full match.
/// Use .next() to get only the first match.
pub fn %s(input: &[u8], offset: usize) -> %s<'_> {
    %s { input, offset, prev_end: None }
}

`, iterName, iterName, slotCount, ffiName, btOverflow, btOverflowMsg(funcName), numGroups, numGroups, funcName, iterName, iterName)
}

// genRustNamedGroupsIterStub generates a named-capture-groups iterator.
// exportName is the actual WASM export name.
// declareFFI controls whether the extern "C" block is emitted; pass false when
// a sibling groups stub in the same file already declared it.
func genRustNamedGroupsIterStub(importModule, funcName, exportName string, declareFFI bool, numGroups int, namedGroups map[string]int) string {
	ffiName := "ffi_" + exportName
	slotCount := numGroups * 2

	type entry struct {
		name  string
		index int
	}
	var entries []entry
	for name, idx := range namedGroups {
		entries = append(entries, entry{name, idx})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].index < entries[j].index })

	var inserts strings.Builder
	for _, e := range entries {
		fmt.Fprintf(&inserts,
			"            if slots[%d] >= 0 { map.insert(\"%s\", (slots[%d] as usize, slots[%d] as usize)); }\n",
			e.index*2, e.name, e.index*2, e.index*2+1)
	}

	var ffiDecl string
	if declareFFI {
		ffiDecl = fmt.Sprintf(`#[link(wasm_import_module = "%s")]
unsafe extern "C" {
    #[link_name = "%s"]
    fn %s(ptr: *const u8, len: usize, out: *mut i32) -> i32;
}

`, importModule, exportName, ffiName)
	}

	iterName := iterTypeName(funcName)
	return ffiDecl + fmt.Sprintf(`pub struct %s<'a> {
    input: &'a [u8],
    offset: usize,
    /// End of the last REPORTED match, for Go's adjacent-empty rule.
    prev_end: Option<usize>,
}

impl<'a> Iterator for %s<'a> {
    type Item = std::collections::HashMap<&'static str, (usize, usize)>;

    fn next(&mut self) -> Option<std::collections::HashMap<&'static str, (usize, usize)>> {
        loop {
            if self.offset > self.input.len() {
                return None;
            }
            let mut slots = [-1i32; %d];
            let r = unsafe { %s(self.input.as_ptr(), self.input.len(), slots.as_mut_ptr(), self.offset) };
            if r == %d {
                panic!("%s");
            }
            if r < 0 {
                if self.offset == self.input.len() {
                    return None;
                }
                self.offset += 1;
                continue;
            }
            // Slots are ABSOLUTE: the whole input is passed on every call.
            let abs_start = slots[0] as usize;
            let abs_end = if slots[1] >= 0 { slots[1] as usize } else { abs_start };
            self.offset = if abs_end > abs_start { abs_end } else { abs_start + 1 };
            let mut map = std::collections::HashMap::new();
%s            return Some(map);
        }
    }
}

/// Returns an iterator over all non-overlapping named-capture matches in input.
/// Group positions are absolute byte offsets.
/// Use .next() to get only the first match.
pub fn %s(input: &[u8], offset: usize) -> %s<'_> {
    %s { input, offset, prev_end: None }
}

`, iterName, iterName, slotCount, ffiName, btOverflow, btOverflowMsg(funcName), inserts.String(), funcName, iterName, iterName)
}
