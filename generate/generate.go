// The first lines of every file a generator writes. The second is the licence
// notice: a stub is regexped's own text copied into the user's output, which
// LICENSE-EXCEPTION frees, and saying so IN the file makes the permission
// travel with it.
const (
	generatedLine   = "Auto-generated by regexped. Do not edit."
	outputTermsLine = "You may use, modify and distribute this file under terms of your choice (regexped LICENSE-EXCEPTION)."
	// lineCommentHeader is both lines as `//` comments.
	lineCommentHeader = "// " + generatedLine + "\n// " + outputTermsLine + "\n"
	// blockCommentHeader is both lines as one C block comment.
	blockCommentHeader = "/* " + generatedLine + "\n   " + outputTermsLine + " */\n"
)

// ResolveStubType determines the stub type from cfg.StubType or the extension
// of cfg.StubFile. Returns one of "rust", "go", "js", "ts", "c", "as", or an error.
//
// The implementation lives in config because config.ValidateConfig needs the
// same answer to run its per-stub-type checks, and a
// second copy could drift from this one — at which point a config would be
// validated against one generator and then generated by another.
func ResolveStubType(cfg config.BuildConfig) (string, error) {
	return config.ResolveStubType(cfg)
}

// ForOutput is cfg as `generate -o out` generates it. stub_type, when set,
// decides the language; otherwise the extension of the path written does —
// out when given, else stub_file ("-" names no file, so stub_file's). The
// export names are checked again for that language when it is not the one
// the config was loaded for: `-o x.go` with `stub_file: s.rs` used to write
// Rust into x.go. So is the language against wasm_format, as LoadConfig checks
// stub_file's: `-o s.js` under a component config wrote a JS loader for a
// module the build does not produce, and `-o x.wit` under a module config a
// WIT for a component it does not.
func ForOutput(cfg config.BuildConfig, out string) (config.BuildConfig, error) {
	if out == "" || out == "-" || cfg.StubType != "" || out == cfg.StubFile {
		return cfg, nil
	}
	c := cfg
	c.StubFile = out
	stubType, err := ResolveStubType(c)
	if err != nil {
		return cfg, err
	}
	if err := config.ValidateStubTypeForFormat(&c, stubType); err != nil {
		return cfg, err
	}
	if err := config.ValidateConfig(&c); err != nil {
		return cfg, err
	}
	return c, nil
}

// CmdGenerateStub generates a stub file of the appropriate type for cfg.
// out is the full output path or "-" for stdout.
func CmdGenerateStub(cfg config.BuildConfig, out string) error {
	// Its stub would call a groups export the module does not have; `compile`
	// refuses the same entry (compile.ErrNoCaptureGroup).
	for _, re := range cfg.Patterns {
		if re.GroupsWithoutCaptures() {
			return fmt.Errorf("pattern %q: groups_func %q: %s", re.Written(), re.GroupsFunc, config.NoCaptureGroupProblem)
		}
	}
	stubType, err := ResolveStubType(cfg)
	if err != nil {
		return err
	}
	// A stub that declares WASM imports needs a name to import FROM, and a
	// Rust or Go stub needs one for its `pub mod` / `package`.
	//
	// MODULE format only. A component imports nothing by module name: its
	// imports are the WIT interface `regexped:<wit_package>/...`, which
	// config.LoadConfig already requires — from `import_module` OR from
	// `wit_package`, so demanding `import_module` here would reject a
	// wit_package-only config that compiles fine. The one name a component
	// stub still needs is Rust's module identifier, which has its own key.
	// Here, not in the command, so `regexped check` makes the same test.
	switch {
	case !cfg.Component():
		if (stubType == "rust" || stubType == "go" || stubType == "c" || stubType == "as") && cfg.ImportModule == "" {
			return errors.New("generate: import_module is required in config for Rust, Go, C, and AS stubs")
		}
	case stubType == "rust" && cfg.RustModuleName() == "":
		return errors.New("generate: rust_module (or import_module) is required in config for Rust stubs: it names the generated `pub mod`")
	}
	return generateStub(cfg, stubType, out)
}

// generateStub dispatches a RESOLVED stub type.
//
// Split from CmdGenerateStub so that the unknown-type arm is reachable from a
// test. config.ResolveStubType cannot produce one today — it returns exactly
// one of the seven names below, or an error — but the arm is the net under
// adding an eighth there and forgetting it here, and an arm nothing can call is
// an arm nothing can prove still reports rather than silently writing the wrong
// language.
func generateStub(cfg config.BuildConfig, stubType, out string) error {
	switch stubType {
	case "rust":
		// The component stub has the same public API and a different body; see
		// generate/rust_component_stub.go.
		if cfg.Component() {
			return rustComponentStub(cfg, out)
		}
		return rustStub(cfg, out)
	case "js":
		return jsStub(cfg, out)
	case "ts":
		return tsStub(cfg, out)
	case "go":
		return goStub(cfg, out)
	case "c":
		if cfg.Component() {
			return cComponentStub(cfg, out)
		}
		return cStub(cfg, out)
	case "as":
		return asStub(cfg, out)
	case "wit":
		return witStub(cfg, out)
	}
	return fmt.Errorf("unknown stub type: %s", stubType)
}

// writeStub creates the parent directory and writes data to path.
//
// Every generator funnels through here — each stub type, both of C's files, and
// the C component stub's wit/consumer.wit and wit/deps/<pkg>.wit — so it is the
// one place stub ownership has to be settled. See internal/ownership.
func writeStub(path string, data []byte) error {
	if err := ownership.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	ownership.Fix(path)
	slog.Info("Written stub", "file", path)
	return nil
}

// extractGroupInfo parses the pattern and returns:
// - numGroups: total number of capture groups including group 0
// - namedGroups: map from name to group index (1-based) for named groups
func extractGroupInfo(pattern string) (int, map[string]int, error) {
	re, err := syntax.Parse(pattern, syntax.Perl)
	if err != nil {
		return 0, nil, fmt.Errorf("parse pattern: %w", err)
	}
	numGroups := re.MaxCap() + 1 // +1 for group 0
	named := make(map[string]int)
	collectNamedGroups(re, named)
	return numGroups, named, nil
}

func collectNamedGroups(re *syntax.Regexp, named map[string]int) {
	if re.Op == syntax.OpCapture && re.Name != "" {
		named[re.Name] = re.Cap
	}
	for _, sub := range re.Sub {
		collectNamedGroups(sub, named)
	}
}
