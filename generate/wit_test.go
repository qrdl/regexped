// The generated text must be WIT that the real toolchain accepts, not merely
// plausible. Skipped rather than failed when wasm-tools is absent, per the
// compile package's convention.
func TestWitRoundTripsThroughWasmTools(t *testing.T) {
	tool, err := exec.LookPath("wasm-tools")
	if err != nil {
		t.Skip("wasm-tools not in PATH; skipping WIT round-trip")
	}
	for _, version := range []string{"", "2.3.0"} {
		cfg := componentCfg()
		cfg.WitVersion = version
		text, err := WitText(cfg)
		if err != nil {
			t.Fatal(err)
		}
		path := filepath.Join(t.TempDir(), "gen.wit")
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
		out, err := exec.Command(tool, "component", "wit", path).CombinedOutput()
		if err != nil {
			t.Fatalf("wasm-tools rejected the generated WIT (version %q): %v\n%s\n--- generated ---\n%s",
				version, err, out, text)
		}
	}
}

